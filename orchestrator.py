def jellyfin_refresh(cfg, media_path, title=None):
    """Fire-and-forget Jellyfin library refresh for a subtitle event.

    Finds the episode item by SearchTerm (=episode title, fallback filename),
    matches Path against the media file (mapped NAS path), then POSTs
    /Items/{id}/Refresh (204). Runs in a daemon thread, ~5s timeouts; failures
    are logged but never fail the episode. No-op without JELLYFIN_API_KEY.
    """
    key = cfg.get("JELLYFIN_API_KEY", "")
    if not key or not media_path:
        return

    def _run():
        try:
            base = (cfg.get("JELLYFIN_URL") or JELLYFIN_URL).rstrip("/")
            root = cfg.get("JELLYFIN_MEDIA_ROOT") or JELLYFIN_MEDIA_ROOT
            jelly_path = (
                root + media_path[len("/mnt/nas/share/media"):]
                if media_path.startswith("/mnt/nas/share/media")
                else media_path
            )
            filename = os.path.basename(media_path)
            headers = {"X-Emby-Token": key}
            r = requests.get(
                base + "/Items",
                params={
                    "Recursive": "true",
                    "IncludeItemTypes": "Episode",
                    "SearchTerm": title or filename,
                    "Fields": "Path,MediaStreams",
                },
                headers=headers,
                timeout=5,
            )
            r.raise_for_status()
            item = None
            for it in r.json().get("Items", []):
                p = it.get("Path") or ""
                if p == jelly_path or p.endswith("/" + filename):
                    item = it
                    break
            if item is None:
                log(f"jellyfin: episode item not found for {filename}")
                return
            body = {
                "MetadataRefreshMode": "FullRefresh",
                "ImageRefreshMode": "None",
                "ReplaceAllMetadata": False,
                "ReplaceAllImages": False,
            }
            rr = requests.post(
                base + f"/Items/{item['Id']}/Refresh",
                json=body,
                headers=headers,
                timeout=5,
            )
            log(f"jellyfin: refresh {filename} HTTP {rr.status_code}")
        except Exception as exc:
            log(f"jellyfin: refresh failed for {media_path}: {exc}")

    threading.Thread(target=_run, daemon=True).start()


def _delete_episode_subtitles(cfg, ep_id, langs=None):
    """Remove {video stem}.{lang}.srt files (NAS path) plus TMP_DIR copies
    the pipeline wrote for the episode. langs=None deletes all TARGET_LANGS;
    otherwise only the listed languages. Never raises."""
    deleted = []
    langs = langs or list(cfg.get("TARGET_LANGS", []))
    try:
        info = get_episode(cfg, ep_id)
        ef = info.get("episodeFile") or {}
        p = map_path(ef.get("path", "")) if ef.get("path") else ""
        if p and os.path.isfile(p):
            stem = os.path.splitext(p)[0]
            for lang in langs:
                cand = f"{stem}.{lang}.srt"
                if os.path.isfile(cand):
                    try:
                        os.remove(cand)
                        deleted.append(cand)
                    except OSError:
                        pass
    except Exception as exc:
        log(f"action: delete: locating episode {ep_id} failed: {exc}")
    for lang in langs:
        cand = os.path.join(cfg.get("TMP_DIR", "/tmp"), f"{ep_id}_{lang}.srt")
        if os.path.isfile(cand):
            try:
                os.remove(cand)
                deleted.append(cand)
            except OSError:
                pass
    return deleted


def consume_actions(cfg):
    """Process pending actions.jsonl records once per pass; consumed records
    removed in place (tail-preserving: records appended mid-pass survive).

    schema (dashboard control_api_v2): {"ts", "type": "retry"|"skip"|"delete",
    "episode_id": int, "language": null|<code>, "source", "note"} —
    "action" is accepted as an alias for "type", and "language" limits retry
    to specific languages (null = the whole episode).

    - skip:   episode excluded from this pass's candidates
    - retry:  state entries cleared AND the episode's subtitle files removed
              (same _delete_episode_subtitles as delete): Bazarr wanted only
              lists episodes with MISSING subtitles, so clearing state alone
              would never reprocess an episode whose .srt is on disk
              (dashboard Retry would be dead); with the file gone the episode
              re-enters Bazarr wanted and is regenerated. "language" limits
              the state clearing AND the subtitle-file deletion to matching
              languages (null = whole episode).
    - delete: NAS + TMP SRT files removed, done state cleared -> regenerates,
              then Jellyfin refresh so the removed subtitle is dropped.
              "language" scopes the file deletion and state clearing to
              matching languages (null = whole episode), like retry.
    Returns the set of episode ids to exclude this pass (skips)."""
    records = consume_records_jsonl(ACTIONS_FILE)
    if not records:
        return set()
    skip_ids, retry_ids, delete_ids = set(), set(), set()
    retry_langs = {}
    delete_langs = {}
    for rec in records:
        eid = rec.get("episode_id")
        if not isinstance(eid, int):
            continue
        action = rec.get("type") or rec.get("action") or ""
        if action == "skip":
            skip_ids.add(eid)
        elif action in ("retry", "delete"):
            ids = retry_ids if action == "retry" else delete_ids
            langs = retry_langs if action == "retry" else delete_langs
            ids.add(eid)
            lang = rec.get("language")
            entry = langs.setdefault(eid, set())
            if isinstance(lang, str) and lang:
                entry.add(lang)
            else:
                entry.add(None)  # null language = whole episode
    if retry_ids or delete_ids:
        states = load_state()
        kept = []
        changed = False
        for e in states:
            eid = e.get("sonarrEpisodeId")
            lang = e.get("language")
            drop = False
            if isinstance(eid, int) and eid in retry_ids:
                langs = retry_langs.get(eid)
                drop = not langs or (None in langs) or (lang in langs)
            elif isinstance(eid, int) and eid in delete_ids:
                langs = delete_langs.get(eid)
                drop = not langs or (None in langs) or (lang in langs)
            if drop:
                changed = True
            else:
                kept.append(e)
        if changed:
            rewrite_jsonl(STATE_FILE, kept)
    for eid in sorted(delete_ids):
        langs = delete_langs.get(eid)
        all_langs = not langs or None in langs
        deleted = _delete_episode_subtitles(
            cfg, eid, langs=None if all_langs else sorted(langs)
        )
        log(f"action: delete episode {eid} (removed {len(deleted)} SRTs, state cleared)")
        media_path, title = "", None
        try:
            info = get_episode(cfg, eid)
            ef = info.get("episodeFile") or {}
            media_path = map_path(ef.get("path", "")) if ef.get("path") else ""
            title = info.get("title") or info.get("Name")
        except Exception:
            pass
        if media_path:
            jellyfin_refresh(cfg, media_path, title)
    for eid in sorted(retry_ids):
        langs = retry_langs.get(eid)
        all_langs = not langs or None in langs
        deleted = _delete_episode_subtitles(
            cfg, eid, langs=None if all_langs else sorted(langs)
        )
        log(f"action: retry episode {eid} (state cleared, {len(deleted)} SRTs removed)")
    for eid in sorted(skip_ids):
        log(f"action: skip episode {eid} (excluded this pass)")
    return skip_ids


def upload_srt(cfg, series_id, ep_id, lang, srt_bytes, filename="sub.srt"):
    """Manual upload via POST /api/episodes/subtitles (verified against live
    Bazarr swagger.json 2026-08-07): query seriesid/episodeid/language/
    forced/hi + multipart file. Movies use POST /api/movies/subtitles
    (radarrid) — not used (Sonarr-only pipeline). Bazarr ignores the uploaded
    filename (subliminal writes {video stem}.{lang alpha2}.srt), and the
    endpoint has no comment/history field, so AI provenance lives only in the
    first SRT cue."""
    url = cfg["BAZARR_URL"].rstrip("/") + "/episodes/subtitles"
    params = {
        "seriesid": series_id,
        "episodeid": ep_id,
        "language": lang,
        "forced": "false",
        "hi": "false",
    }
    headers = {"X-API-KEY": cfg["BAZARR_API_KEY"]}
    files = {"file": (filename, srt_bytes, "application/x-subrip")}
    last_code = None
    for attempt in range(3):
        try:
            r = requests.post(
                url, params=params, headers=headers, files=files, timeout=120
            )
            last_code = r.status_code
            if r.status_code == 204:
                return 204
            log(
                f"    [upload] HTTP {r.status_code} (attempt {attempt + 1}): {r.text[:200]}"
            )
        except requests.RequestException as exc:
            last_code = None
            log(f"    [upload] network error (attempt {attempt + 1}): {exc}")
        if attempt < 2:
            time.sleep(5 * (attempt + 1))
    return last_code


def notify_hermes(cfg, ep_id, lang, series, tag, exc):
    global _GLOBAL_HELP_LAST
    try:
        url = cfg.get("HERMES_WEBHOOK_URL", "")
        secret = cfg.get("HERMES_WEBHOOK_SECRET", "")
        if not url or not secret:
            return
        now = time.time()
        last = _HELP_COOLDOWN.get((ep_id, lang), 0)
        if now - last < 1800:
            return
        if now - _GLOBAL_HELP_LAST < 600:
            log("help: throttled (global)")
            return
        payload = {
            "event_type": "pipeline_error",
            "episode": f"{tag} {series}",
            "lang": lang,
            "error": str(exc)[:500],
            "log_tail": list(_LOG_RING),
        }
        body = json.dumps(payload).encode()
        ts = str(int(time.time()))
        sig = hmac.new(
            secret.encode(), ts.encode() + b"." + body, hashlib.sha256
        ).hexdigest()
        headers = {
            "X-Webhook-Signature-V2": sig,
            "X-Webhook-Timestamp": ts,
            "Content-Type": "application/json",
        }
        r = requests.post(url, data=body, headers=headers, timeout=10)
        if r.status_code in (200, 202):
            _HELP_COOLDOWN[(ep_id, lang)] = time.time()
            _GLOBAL_HELP_LAST = time.time()
            log(f"help: {tag} {series} [{lang}] notified Hermes")
        else:
            log(f"help: notify failed: HTTP {r.status_code}")
    except Exception as e:
        log(f"help: notify failed: {e}")


def process_after_asr(
    cfg,
    key,
    ep_id,
    lang,
    series,
    tag,
    src,
    t0,
    cues,
    decision,
    info,
    wav_path,
    srt_path,
    prior_cache=None,
):
    global _paused
    try:
        if decision["needs_translate"]:
            t_tr = time.time()
            if not key and not is_local_translate(cfg):
                raise RuntimeError("translate needed but TRANSLATE_API_KEY empty")
            groups = translate_texts(
                cfg,
                cues,
                lang,
                key,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                prior_cache,
                series_title=series,
            )
            if groups is None:
                raise RuntimeError("translation failed")
            cues_out = []
            texts_out = []
            for s, e, t in groups:
                cues_out.append({"start": cues[s]["start"], "end": cues[e - 1]["end"]})
                texts_out.append(t)
            tr_elapsed = time.time() - t_tr
            log(
                f"  {tag} [{src}->{lang}] translate {tr_elapsed:.0f}s, {len(texts_out)} lines"
            )
        else:
            cues_out = cues
            texts_out = [c["text"] for c in cues]

        write_srt(cues_out, texts_out, srt_path, header=AI_MARKER)
        with open(srt_path, "rb") as fh:
            srt_bytes = fh.read()
        code = upload_srt(
            cfg,
            info.get("seriesId") or info.get("sonarrSeriesId"),
            ep_id,
            lang,
            srt_bytes,
            filename=os.path.basename(srt_path),
        )
        if code != 204:
            raise RuntimeError(f"upload HTTP {code} (expected 204)")
        ef = info.get("episodeFile") or {}
        if ef.get("path"):
            jellyfin_refresh(cfg, map_path(ef["path"]), info.get("title") or info.get("Name"))
        elapsed = round(time.time() - t0, 1)
        append_state(
            {
                "sonarrEpisodeId": ep_id,
                "language": lang,
                "status": "done",
                "elapsed_s": elapsed,
            }
        )
        log(f"done: {tag} {series} [{src}->{lang}] in {elapsed}s (upload 204)")
        return "done"
    except Exception as exc:
        append_state(
            {
                "sonarrEpisodeId": ep_id,
                "language": lang,
                "status": "error",
                "elapsed_s": round(time.time() - t0, 1),
            }
        )
        log(f"fail: {series} [{lang}] {exc}")
        notify_hermes(cfg, ep_id, lang, series, tag, exc)
        halt_on_error(cfg, "process_episode", f"{series} [{lang}] {tag}", exc)
        return "failed"
    finally:
        for f in (wav_path, srt_path):
            try:
                os.remove(f)
            except OSError:
                pass


