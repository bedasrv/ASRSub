# ---------- job queue registry ----------
#
# Thread-safe registry of submitted jobs. One writer discipline:
# every mutation below happens under _queue_lock. Entries carry an
# explicit "idx" handle (monotonic per clear) so helpers can resolve
# them even after older terminal entries are pruned from the head;
# never address entries by list position outside these helpers.

_QUEUE_MAX = 20
_queue: list = []
_queue_lock = threading.Lock()
_queue_next_idx = 0


def _queue_enqueue(desc):
    """Append a job descriptor as queued; returns its stable idx handle."""
    global _queue_next_idx
    with _queue_lock:
        while len(_queue) >= _QUEUE_MAX and _queue and _queue[0]["state"] in (
            "done",
            "error",
        ):
            _queue.pop(0)  # drop oldest finished entry to stay bounded
        idx = _queue_next_idx
        _queue_next_idx += 1
        # Active jobs may exceed _QUEUE_MAX temporarily; /status slices
        # the payload, so the wire shape stays bounded regardless.
        _queue.append(dict(desc, state="queued", idx=idx))
    return idx


def _queue_find(idx):
    """Return the live entry with this idx handle (call under lock)."""
    for entry in _queue:
        if entry["idx"] == idx:
            return entry
    return None


def _queue_set_running(idx):
    with _queue_lock:
        entry = _queue_find(idx)
        if entry is not None:
            entry["state"] = "running"
            entry["since"] = datetime.now(timezone.utc).isoformat()
            return dict(entry)
    return None


def _queue_finish(idx, ok):
    """Mark terminal outcome and remove the entry (finished jobs vanish)."""
    with _queue_lock:
        entry = _queue_find(idx)
        if entry is not None:
            entry["state"] = "done" if ok else "error"
            _queue.remove(entry)


def _queue_snapshot():
    with _queue_lock:
        return [dict(entry) for entry in _queue]


def _queue_clear():
    global _queue_next_idx
    with _queue_lock:
        _queue.clear()
        _queue_next_idx = 0


def _queue_summary():
    snap = _queue_snapshot()
    return {
        "items": snap[:20],
        "queued_total": sum(1 for j in snap if j["state"] == "queued"),
        "running": bool(any(j["state"] == "running" for j in snap)),
    }


_current = None  # ONLY mutated by _tracked's runner below


class _TrackedCall:
    """Zero-arg callable for pool.submit(_tracked(desc, fn, ...)).

    Also exposes .result(): if the job was never handed to an executor,
    the first .result() runs it inline; otherwise it blocks until the
    executor finishes and mirrors Future.result() semantics (return
    value or raise, verbatim from the wrapped function).
    """

    def __init__(self, run):
        self._run = run
        self._lock = threading.Lock()
        self._done = False
        self._outcome = None
        self._exc = None

    def __call__(self):
        with self._lock:  # execute exactly once, even under both paths
            if not self._done:
                try:
                    self._outcome = self._run()
                except BaseException as exc:
                    self._exc = exc
                    raise
                finally:
                    self._done = True
        if self._exc is not None:
            raise self._exc
        return self._outcome

    def result(self, timeout=None):
        # timeout is accepted for Future compatibility; execution is
        # either already finished or happens now (inline).
        return self.__call__()


def _tracked(desc, fn, *args, **kwargs):
    """Wrap a submitted job: manage queue entry + _current lifecycle.

    Usage (Task 3 wiring): futures.append(pool.submit(_tracked(desc, fn, ...))).
    The wrapper is the ONLY writer of module-global _current: it flips to
    the job's descriptor at actual execution start (not scan time) and
    back to None when the job exits, success or failure.
    """
    idx = _queue_enqueue(desc)

    def _run():
        global _current
        _current = _queue_set_running(idx) or dict(desc, state="running")
        ok = False
        try:
            rc = fn(*args, **kwargs)
            ok = True
            return rc
        finally:
            _current = None
            _queue_finish(idx, ok=ok)

    return _TrackedCall(_run)


