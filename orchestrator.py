_WEBHOOK_COOLDOWN = {}
_WEBHOOK_LOCK = threading.Lock()
_WEBHOOK_EVENT_COOLDOWN = {
    "pipeline_error": 1800,  # per ep_key; plus 600s global
    "subtitle_done": 60,     # per ep_key
    "pass_completed": 300,   # global
}


def _webhook_urls(cfg):
    """Configured outbound webhook URLs. WEBHOOK_URLS (comma list) wins;
    the legacy HERMES_WEBHOOK_URL is used when unset."""
    urls = [
        u.strip()
        for u in str(cfg.get("WEBHOOK_URLS") or "").split(",")
        if u.strip()
    ]
    if not urls:
        legacy = (cfg.get("HERMES_WEBHOOK_URL") or "").strip()
        if legacy:
            urls = [legacy]
    return urls


def _webhook_secret(cfg):
    return cfg.get("WEBHOOK_SECRET") or cfg.get("HERMES_WEBHOOK_SECRET") or ""


def _webhook_events(cfg):
    """Enabled event types; empty/unset = all."""
    raw = cfg.get("WEBHOOK_EVENTS")
    if raw is None or not str(raw).strip():
        return {"subtitle_done", "pipeline_error", "pass_completed"}
    return {e.strip() for e in str(raw).split(",") if e.strip()}


def notify_webhook(cfg, event_type, payload, ep_key=None):
    """Fire-and-forget HMAC-signed webhook POST to every configured URL.

    Signature (unchanged from notify_hermes):
      X-Webhook-Signature-V2 = hmac_sha256_hex(secret, "<ts>.<body>")
      X-Webhook-Timestamp = str(int(time.time()))
    Retries twice on network error / 5xx with 2s/5s backoff. Per-event
    cooldowns: pipeline_error 1800s per ep_key + 600s global; subtitle_done
    60s per ep_key; pass_completed 300s global. Never raises, never blocks
    (daemon thread)."""
    try:
        urls = _webhook_urls(cfg)
        secret = _webhook_secret(cfg)
        if not urls or not secret:
            return
        if event_type not in _webhook_events(cfg):
            return
    except Exception:
        return

    global _GLOBAL_HELP_LAST
    now = time.time()
    if event_type == "pipeline_error":
        with _WEBHOOK_LOCK:
            last = _HELP_COOLDOWN.get(ep_key, 0.0)
        if now - last < 1800:
            return
        with _WEBHOOK_LOCK:
            if now - _GLOBAL_HELP_LAST < 600:
                log("webhook: pipeline_error throttled (global)")
                return
    elif event_type == "subtitle_done":
        with _WEBHOOK_LOCK:
            last = _WEBHOOK_COOLDOWN.get(("subtitle_done",) + tuple(ep_key or ()), 0.0)
        if now - last < 60:
            return
    elif event_type == "pass_completed":
        with _WEBHOOK_LOCK:
            last = _WEBHOOK_COOLDOWN.get(("pass_completed",), 0.0)
        if now - last < 300:
            return

    def _run():
        global _GLOBAL_HELP_LAST
        for url in urls:
            try:
                body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
                ts = str(int(time.time()))
                sig = hmac.new(
                    secret.encode(), ts.encode() + b"." + body, hashlib.sha256
                ).hexdigest()
                headers = {
                    "X-Webhook-Signature-V2": sig,
                    "X-Webhook-Timestamp": ts,
                    "Content-Type": "application/json",
                }
                code = None
                for attempt in range(3):
                    try:
                        r = requests.post(url, data=body, headers=headers, timeout=10)
                        code = r.status_code
                        if code < 500:
                            break
                    except requests.RequestException:
                        code = None
                    if attempt < 2:
                        time.sleep(2 if attempt == 0 else 5)
                if code is None:
                    log(f"webhook: {event_type} -> {url} failed: network error")
                elif code in (200, 202, 204):
                    log(f"webhook: {event_type} -> {url} HTTP {code}")
                    if event_type == "pipeline_error":
                        with _WEBHOOK_LOCK:
                            if ep_key:
                                _HELP_COOLDOWN[ep_key] = time.time()
                            _GLOBAL_HELP_LAST = time.time()
                    elif event_type == "subtitle_done" and ep_key:
                        with _WEBHOOK_LOCK:
                            _WEBHOOK_COOLDOWN[
                                ("subtitle_done",) + tuple(ep_key)
                            ] = time.time()
                    elif event_type == "pass_completed":
                        with _WEBHOOK_LOCK:
                            _WEBHOOK_COOLDOWN[("pass_completed",)] = time.time()
                else:
                    log(f"webhook: {event_type} -> {url} failed: HTTP {code}")
            except Exception as exc:
                log(f"webhook: {event_type} -> {url} failed: {exc}")

    threading.Thread(target=_run, daemon=True).start()


def notify_hermes(cfg, ep_id, lang, series, tag, exc):
    """Legacy Hermes error notifier — thin wrapper over the generalized
    notify_webhook (pipeline_error event, same payload shape + cooldowns)."""
    notify_webhook(
        cfg,
        "pipeline_error",
        {
            "event_type": "pipeline_error",
            "episode": f"{tag} {series}",
            "lang": lang,
            "error": str(exc)[:500],
            "log_tail": list(_LOG_RING),
        },
        ep_key=(ep_id, lang),
    )


def process_after_asr(
    cfg,
    key,
    ep_id,
    lang,
    series,
    tag,
    src,
    t0,
    cues,
    decision,
    info,
    wav_path,
    srt_path,
    prior_cache=None,
    movie_id=None,
):
    global _paused
    try:
        if decision["needs_translate"]:
            t_tr = time.time()
            if not key and not is_local_translate(cfg):
                raise RuntimeError("translate needed but TRANSLATE_API_KEY empty")
            groups = translate_texts(
                cfg,
                cues,
                lang,
                key,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                prior_cache,
                series_title=series,
                skip_guard=(decision.get("asr_lang") == "en"),
            )
            if groups is None:
                raise RuntimeError("translation failed")
            cues_out = []
            texts_out = []
            for s, e, t in groups:
                cues_out.append({"start": cues[s]["start"], "end": cues[e - 1]["end"]})
                texts_out.append(t)
            tr_elapsed = time.time() - t_tr
            log(
                f"  {tag} [{src}->{lang}] translate {tr_elapsed:.0f}s, {len(texts_out)} lines"
            )
        else:
            cues_out = cues
            texts_out = [c["text"] for c in cues]

        # ASR-translated output only: merge too-fast translated cues with the
        # following cue so the reading speed stays within max_cps (ladder
        # output never passes through here — it writes at its own call site).
        merged = cps_merge(
            [
                {"start": c["start"], "end": c["end"], "text": t}
                for c, t in zip(cues_out, texts_out)
            ]
        )
        cues_out = [{"start": c["start"], "end": c["end"]} for c in merged]
        texts_out = [c["text"] for c in merged]

        write_srt(cues_out, texts_out, srt_path, header=AI_MARKER)
        with open(srt_path, "rb") as fh:
            srt_bytes = fh.read()
        media_path = map_path((info.get("episodeFile") or {}).get("path", "")) or None
        if movie_id is not None:
            code = upload_srt_movie(
                cfg, movie_id, lang, srt_bytes, filename=os.path.basename(srt_path),
                media_path=media_path,
            )
        else:
            code = upload_srt(
                cfg,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                lang,
                srt_bytes,
                filename=os.path.basename(srt_path),
                media_path=media_path,
            )
        if code != 204:
            raise RuntimeError(f"upload HTTP {code} (expected 204)")
        ef = info.get("episodeFile") or {}
        if ef.get("path"):
            jellyfin_refresh(
                cfg,
                map_path(ef["path"]),
                info.get("title") or info.get("Name"),
                item_type="Movie" if movie_id is not None else "Episode",
            )
        elapsed = round(time.time() - t0, 1)
        stem = os.path.splitext(map_path((info.get("episodeFile") or {}).get("path", "")))[0] or None
        registry_upsert(stem, lang, "asr", ep_id=ep_id, kind=("movie" if movie_id is not None else None))
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "done",
            "elapsed_s": elapsed,
            "source": "asr",
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        log(f"done: {tag} {series} [{src}->{lang}] in {elapsed}s (upload 204)")
        notify_webhook(
            cfg,
            "subtitle_done",
            {
                "event_type": "subtitle_done",
                "episode": f"{tag} {series}",
                "lang": lang,
                "source": "asr",
                "duration_s": int(elapsed),
                "status_code": code,
            },
            ep_key=(ep_id, lang),
        )
        return "done"
    except Exception as exc:
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "error",
            "elapsed_s": round(time.time() - t0, 1),
            "source": "asr",
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        log(f"fail: {series} [{lang}] {exc}")
        notify_hermes(cfg, ep_id, lang, series, tag, exc)
        halt_on_error(cfg, "process_episode", f"{series} [{lang}] {tag}", exc)
        return "failed"
    finally:
        for f in (wav_path, srt_path):
            try:
                os.remove(f)
            except OSError:
                pass


def process_ladder(
    cfg,
    key,
    ep_id,
    lang,
    series,
    tag,
    source,
    info,
    prior_cache=None,
    movie_id=None,
):
    """Ladder translation: translate from an existing jpn/eng subtitle source
    (SKIP ASR entirely), write {stem}.{lang}.srt next to the video with the AI
    marker cue, register the source in the registry and wake Jellyfin. An eng
    source satisfying the en target is adopted verbatim (no marker: it is not
    AI-generated text, but ownership is still registry-tracked). Returns
    "done" or "failed". movie_id (radarr track): uploads via the movies
    endpoint, state rows carry kind "movie", and the Jellyfin refresh searches
    Movie items; None keeps series behavior."""
    t0 = time.time()
    kind = source["kind"]
    try:
        media_path = map_path((info.get("episodeFile") or {}).get("path", ""))
        if not media_path or not os.path.isfile(media_path):
            raise RuntimeError(f"media file missing: {media_path}")
        cues = source["cues"] or []
        if not cues:
            raise RuntimeError("ladder source produced no cues")
        srt_path = os.path.splitext(media_path)[0] + f".{lang}.srt"
        needs_translate = not ((kind == "eng" and lang == "en") or (kind in ("jpn", "asr") and lang == "ja"))
        if needs_translate:
            if not key and not is_local_translate(cfg):
                raise RuntimeError("translate needed but TRANSLATE_API_KEY empty")
            t_tr = time.time()
            groups = translate_texts(
                cfg,
                cues,
                lang,
                key,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                prior_cache,
                series_title=series,
                skip_guard=(kind == "eng"),
            )
            if groups is None:
                raise RuntimeError("translation failed")
            cues_out = []
            texts_out = []
            for s, e, t in groups:
                cues_out.append({"start": cues[s]["start"], "end": cues[e - 1]["end"]})
                texts_out.append(t)
            log(
                f"  {tag} [{kind}->{lang}] translate {time.time() - t_tr:.0f}s, {len(texts_out)} lines"
            )
            header = AI_MARKER
        else:
            cues_out = cues
            texts_out = [c["text"] for c in cues]
            header = None
        tmp = srt_path + ".ladder.tmp"
        write_srt(cues_out, texts_out, tmp, header=header)
        os.replace(tmp, srt_path)
        with open(srt_path, "rb") as fh:
            srt_bytes = fh.read()
        if movie_id is not None:
            code = upload_srt_movie(
                cfg, movie_id, lang, srt_bytes, filename=os.path.basename(srt_path),
                media_path=media_path,
            )
        else:
            code = upload_srt(
                cfg,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                lang,
                srt_bytes,
                filename=os.path.basename(srt_path),
                media_path=media_path,
            )
        if code != 204:
            raise RuntimeError(f"upload HTTP {code} (expected 204)")
        stem = os.path.splitext(media_path)[0]
        # Registry the produced {stem}.{lang}.srt with the SOURCE's
        # provenance: when the ladder used an on-disk sidecar that still
        # matches its own registry row (webhook embedded extraction, hash
        # untouched), PRESERVE the row's source_kind instead of flipping it
        # to "external" — a webhook-extracted sidecar is aligned by
        # construction even when consumed from disk. "external" only when
        # the sidecar was clobbered (hash mismatch) or never registered.
        # A tmp extraction is embedded by construction and never clobbers
        # the on-disk sidecar's own row.
        src_row = registry_get(stem, kind)
        if source.get("tmp"):
            source_kind = "embedded"
        elif (
            src_row
            and src_row.get("source_hash")
            and src_row["source_hash"] == source["source_hash"]
        ):
            source_kind = src_row.get("source_kind") or "external"
        else:
            source_kind = "external"
        registry_upsert(
            stem,
            lang,
            kind,
            source_path=source["source_path"],
            source_hash=source["source_hash"],
            source_kind=source_kind,
            ep_id=ep_id,
            retimed=source.get("align_stats", {}).get("method"),
            matched_frac=source.get("align_stats", {}).get("matched_frac"),
            kind=("movie" if movie_id is not None else None),
        )
        elapsed = round(time.time() - t0, 1)
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "done",
            "elapsed_s": elapsed,
            "source": kind,
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        jellyfin_refresh(
            cfg,
            media_path,
            info.get("title") or info.get("Name"),
            item_type="Movie" if movie_id is not None else "Episode",
        )
        log(f"done: {tag} {series} [{kind}->{lang}] in {elapsed}s (upload 204, ladder)")
        notify_webhook(
            cfg,
            "subtitle_done",
            {
                "event_type": "subtitle_done",
                "episode": f"{tag} {series}",
                "lang": lang,
                "source": kind,
                "duration_s": int(elapsed),
                "status_code": code,
            },
            ep_key=(ep_id, lang),
        )
        return "done"
    except Exception as exc:
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "error",
            "elapsed_s": round(time.time() - t0, 1),
            "source": kind,
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        log(f"fail: {series} [{lang}] {exc}")
        notify_hermes(cfg, ep_id, lang, series, tag, exc)
        halt_on_error(cfg, "process_ladder", f"{series} [{lang}] {tag}", exc)
        return "failed"
    finally:
        if source.get("tmp") and source.get("source_path"):
            try:
                os.remove(source["source_path"])
            except OSError:
                pass
        if source.get("align_tmp"):
            _silent_remove(source["align_tmp"])


def run_upgrades(cfg, key, prior_cache=None):
    """Auto-upgrade pass: AI-owned subs produced from ASR/eng/jpn get
    re-translated from a better jpn source when one appears — including rows
    whose current output came from a jpn source (source 'jpn': a Jimaku .ja
    sidecar that arrived after generation, adopted verbatim or translated,
    may itself be superseded by a NEWER sidecar; late-arriving better sources
    win automatically). Only OUTPUT languages are eligible (lang in
    TARGET_LANGS) so source-sidecar rows ({stem}.jpn.srt etc., written by the
    webhook/_register_external_sidecar) are never re-processed. Guards: only
    AI-owned subs (registry authoritative, marker fallback), refine-history
    skip (LADDER_SKIP_REFINED), source-hash dedup (re-translation only when
    the jpn source file actually changed/new), per-episode cooldown +
    per-pass upgrade budget (LADDER_UPGRADE_BUDGET). Rows oldest-first.
    Returns {"upgraded": n, "checked": n}."""
    lc = _ladder_cfg(cfg)
    if lc["upgrade_budget"] <= 0:
        return {"upgraded": 0, "checked": 0}
    registry = load_registry()
    refined = load_refined_set() if lc["skip_refined"] else set()
    now = datetime.now(timezone.utc)
    target_langs = set(cfg.get("TARGET_LANGS") or [])
    rows = sorted(
        (
            rec
            for rec in registry.values()
            if rec.get("source") in ("asr", "eng", "jpn")
            and rec.get("lang") in target_langs
        ),
        key=lambda r: r.get("updated_ts") or r.get("created_ts") or "",
    )
    upgraded = 0
    checked = 0
    for rec in rows:
        ep_id = rec.get("episode_id")
        lang = rec.get("lang")
        if upgraded >= lc["upgrade_budget"]:
            break
        if (ep_id, lang) in refined:
            log(f"upgrade: skip {ep_id} [{lang}] refined (refine_history)")
            continue
        updated = rec.get("updated_ts") or rec.get("created_ts") or ""
        try:
            age_h = (
                now - datetime.fromisoformat(updated.replace("Z", "+00:00"))
            ).total_seconds() / 3600
        except Exception:
            age_h = None  # unknown age: eligible
        if age_h is not None and age_h < lc["cooldown_h"]:
            continue
        checked += 1
        try:
            info = get_episode(cfg, ep_id)
        except Exception as exc:
            log(f"upgrade: get_episode {ep_id} failed: {exc}")
            continue
        ef = info.get("episodeFile") or {}
        if not info.get("hasFile") or not ef.get("path"):
            continue
        media_path = map_path(ef["path"])
        if not os.path.isfile(media_path):
            continue
        if not sub_is_ai_owned(registry, ep_id, lang, media_path):
            continue  # foreign sub on disk: never touched
        ladder = detect_ladder_source(
            cfg,
            media_path,
            lang,
            cfg.get("TMP_DIR", "/tmp"),
            ep_id,
            info.get("seriesId") or info.get("sonarrSeriesId"),
            series_title=info.get("seriesTitle") or info.get("title"),
            season=info.get("seasonNumber"),
            episode=info.get("episodeNumber"),
        )
        if ladder["kind"] != "jpn":
            continue
        if (
            rec.get("source_hash")
            and ladder["source_hash"]
            and rec["source_hash"] == ladder["source_hash"]
        ):
            continue  # same source already translated
        season = info.get("seasonNumber", "?")
        ep_num = info.get("episodeNumber", "?")
        tag = (
            f"S{season:02d}E{ep_num:02d}"
            if isinstance(season, int) and isinstance(ep_num, int)
            else f"S{season}E{ep_num}"
        )
        series = info.get("seriesTitle") or info.get("title") or "?"
        status = process_ladder(
            cfg, key, ep_id, lang, series, tag, ladder, info, prior_cache=prior_cache
        )
        if status == "done":
            upgraded += 1
    if checked or upgraded:
        log(
            f"upgrade pass: checked={checked} upgraded={upgraded} "
            f"(budget={lc['upgrade_budget']}, cooldown_h={lc['cooldown_h']})"
        )
    return {"upgraded": upgraded, "checked": checked}


def _jimaku_hunt_backoff_minutes(attempts):
    """Exponential backoff: 30*2^(N-1) capped at 1440 min (24h).
    attempts >=1 -> minutes, attempts <=0 -> 0 (fresh row immediate)."""
    try:
        n = int(attempts)
    except Exception:
        n = 0
    if n <= 0:
        return 0
    return min(30 * (2 ** (n - 1)), 1440)


def _jimaku_hunt_parse_ts(ts_str):
    if not ts_str:
        return None
    try:
        return datetime.fromisoformat(str(ts_str).replace("Z", "+00:00"))
    except Exception:
        return None


def _jimaku_hunt_eligible(rec, now):
    """True when backoff window has elapsed. Fresh rows (no hunt fields)
    are immediately eligible. Backoff = min(30*2^(N-1),1440) minutes."""
    last_ts = rec.get("jimaku_hunt_last_ts")
    attempts = rec.get("jimaku_hunt_attempts")
    try:
        n = int(attempts) if attempts is not None else 0
    except Exception:
        n = 0
    if not last_ts:
        return True
    dt = _jimaku_hunt_parse_ts(last_ts)
    if dt is None:
        return True
    backoff = _jimaku_hunt_backoff_minutes(n if n > 0 else 1)
    # fresh row with no attempts but with last_ts shouldn't happen; treat as needing 30min
    if n == 0:
        backoff = 30
    elapsed_min = (now - dt).total_seconds() / 60.0
    return elapsed_min >= backoff


def _jimaku_hunt_record_attempt(rec, now):
    """Persist hunt miss tracking on the registry row(s) for this episode.
    Increments jimaku_hunt_attempts and sets jimaku_hunt_last_ts to now.
    Updates all matching asr ja/jpn rows for the same episode_id to keep
    dedup consistent (one hunt per episode, not per stem)."""
    try:
        ep_id = rec.get("episode_id")
        lang = rec.get("lang")
        stem = rec.get("stem") or ""
        # gather all matching rows for this episode to keep them in sync
        try:
            all_recs = list(load_registry().values())
        except Exception:
            all_recs = [rec]
        # filter to same episode_id and ja/jpn asr rows
        targets = []
        for r in all_recs:
            if r.get("episode_id") != ep_id:
                continue
            if r.get("source") != "asr":
                continue
            if r.get("lang") not in ("ja", "jpn"):
                continue
            if r.get("stem"):
                targets.append(r)
        if not targets:
            targets = [rec]
        # dedup by stem+lang
        seen = set()
        for t in targets:
            key = (t.get("stem"), t.get("lang"))
            if key in seen:
                continue
            seen.add(key)
            prev_attempts = t.get("jimaku_hunt_attempts")
            try:
                n = int(prev_attempts) if prev_attempts is not None else 0
            except Exception:
                n = 0
            new_n = n + 1
            now_iso = now.strftime("%Y-%m-%dT%H:%M:%SZ")
            registry_upsert(
                t.get("stem") or stem,
                t.get("lang") or lang,
                t.get("source") or "asr",
                source_path=t.get("source_path"),
                source_hash=t.get("source_hash"),
                source_kind=t.get("source_kind"),
                ep_id=ep_id if isinstance(ep_id, int) else None,
                audio_id=t.get("audio_id"),
                retimed=t.get("retimed"),
                matched_frac=t.get("matched_frac"),
                kind=t.get("kind"),
                jimaku_hunt_last_ts=now_iso,
                jimaku_hunt_attempts=new_n,
            )
    except Exception as exc:
        log(f"WARNING: jimaku hunt: failed to record attempt for ep {rec.get('episode_id')}: {exc}")


def run_jimaku_hunt(cfg, prior_cache=None):
    """Per-pass Jimaku sweep: an episode or movie whose on-disk ja came from ASR
    (registry source 'asr') can never receive real Japanese subs on its own —
    Bazarr recorded the AI upload as a perfect-score manual row its upgrade
    task never revisits, and bazarr-jp only searches Jimaku while ja counts
    as missing. For each eligible episode/movie ask Bazarr to search+download
    jpn again (bazarr_jpn_candidate / bazarr_jpn_movie_candidate with
    return_meta=True); a fresh download lands as a plain {stem}.jpn.srt
    sidecar — no re-timing/registration here, the normal ladder + upgrade pass
    adopts it on subsequent passes.
    Series items try the DIRECT Jimaku path first (jimaku_direct_candidate,
    JIMAKU_DIRECT_ENABLED): resolve + list_files for that episode without
    Bazarr; a fresh {stem}.jpn.srt landing counts as landed and SKIPS the
    Bazarr search for that item. Only when the direct path cannot run or
    finds nothing does the flow fall through to bazarr_jpn_candidate below.
    Movies stay on the Bazarr-only path. A Jimaku 429 on the direct path
    aborts the rest of the pass exactly like a Bazarr 429 (no attempt
    counted).
    Guards: per-item exponential backoff on jimaku_hunt_last_ts /
    jimaku_hunt_attempts (30m, 1h, 2h, 4h, 8h, 16h, 24h cap), per-pass budget
    (LADDER_JIMAKU_HUNT_BUDGET, shared with movies; LADDER_JIMAKU_HUNT_BUDGET_MOVIES
    may override for movies, default separate), rows oldest hunt_last_ts first
    (None sorts oldest). The positive _BAZARR_JPN_CACHE / _BAZARR_JPN_MOVIE_CACHE
    entry is dropped for every freshly searched item so later ladder reads
    re-scan disk instead of trusting stale cache. 429 rate limit aborts the rest
    of the pass (WARNING with reset_after, no attempt counted). Tiny sleep (2.5s)
    between searches avoids bursting >24 req/min. prior_cache mirrors run_upgrades
    (unused). Returns {"checked": n, "searched": m, "landed": k}; never raises."""
    lc = _ladder_cfg(cfg)
    if lc["jimaku_hunt_budget"] <= 0:
        return {"checked": 0, "searched": 0, "landed": 0}
    registry = load_registry()
    now = datetime.now(timezone.utc)
    # One hunt per episode/movie: dedup registry rows by (kind, episode_id),
    # the OLDEST updated_ts wins for dedup identity; ordering later uses hunt ts.
    by_series = {}
    by_movie = {}
    for rec in registry.values():
        if rec.get("source") != "asr" or rec.get("lang") not in ("ja", "jpn"):
            continue
        ep_id = rec.get("episode_id")
        if not isinstance(ep_id, int):
            continue
        is_movie = rec.get("kind") == "movie"
        target = by_movie if is_movie else by_series
        cur = target.get(ep_id)
        if cur is None or (rec.get("updated_ts") or "") < (
            cur.get("updated_ts") or ""
        ):
            target[ep_id] = rec
    # Pre-fetch movie path map once (needed for movie rows and for
    # legacy rows without kind where episode_id is a radarrId)
    movie_path_map = {}
    if by_series or by_movie:
        try:
            movies = get_movies(cfg)
            for m in movies.get("data") or []:
                rid = m.get("radarrId")
                if isinstance(rid, int) and m.get("path"):
                    movie_path_map[rid] = map_path(m["path"])
        except Exception as exc:
            log(f"jimaku hunt: get_movies failed: {exc}")
            movie_path_map = {}
    # Legacy fallback: rows without kind whose episode_id matches a known
    # radarrId are movie rows stored before kind-aware registry_upsert
    if movie_path_map:
        for ep_id in list(by_series.keys()):
            if ep_id in movie_path_map and ep_id not in by_movie:
                rec = by_series.pop(ep_id)
                by_movie[ep_id] = rec
    # Build combined oldest-hunt-first list with type flag; budget is shared.
    def _hunt_sort_key(item):
        # item is (rec, kind, ep_id) tuple; sort by hunt_last_ts (None = oldest)
        _, rec = item
        ts = _jimaku_hunt_parse_ts(rec.get("jimaku_hunt_last_ts"))
        if ts is None:
            return (0, "")  # None sorts oldest
        return (1, ts.isoformat())
    series_items = [(ep_id, rec) for ep_id, rec in by_series.items()]
    movie_items = [(ep_id, rec) for ep_id, rec in by_movie.items()]
    # combine for shared ordering
    combined = []
    for ep_id, rec in series_items:
        combined.append(("series", ep_id, rec))
    for ep_id, rec in movie_items:
        combined.append(("movie", ep_id, rec))
    # sort by hunt_last_ts oldest first (None first), then by string fallback for determinism
    def _key(entry):
        kind, ep_id, rec = entry
        ts = _jimaku_hunt_parse_ts(rec.get("jimaku_hunt_last_ts"))
        if ts is None:
            return (0, "", ep_id)
        return (1, ts.isoformat(), ep_id)
    combined.sort(key=_key)
    checked = searched = landed = 0
    movie_searched = 0
    movie_budget = lc.get("jimaku_hunt_budget_movies", lc["jimaku_hunt_budget"])
    abort_429 = False
    for kind, ep_id, rec in combined:
        if abort_429:
            break
        # Shared budget guard; also respect separate movie budget when set
        if searched >= lc["jimaku_hunt_budget"]:
            break
        if kind == "movie" and movie_searched >= movie_budget:
            continue
        if not _jimaku_hunt_eligible(rec, now):
            continue
        checked += 1
        if kind == "movie":
            media_path = movie_path_map.get(ep_id)
            if not media_path or not os.path.isfile(media_path):
                continue
            key = ep_id
            _BAZARR_JPN_MOVIE_TRIED.discard(key)
            try:
                cand, how = bazarr_jpn_movie_candidate(
                    cfg,
                    ep_id,
                    media_path,
                    cfg.get("TMP_DIR", "/tmp"),
                    return_meta=True,
                    allow_existing=False,
                )
            except Exception as exc:
                log(f"jimaku hunt: movie {ep_id} search failed: {exc}")
                continue
            if how == "rate_limited":
                log(f"WARNING: jimaku hunt: aborting remaining hunt due to 429 (movie {ep_id})")
                abort_429 = True
                # do not count attempt
                break
            if how in ("download", "searched"):
                searched += 1
                movie_searched += 1
                _BAZARR_JPN_MOVIE_CACHE.pop(key, None)
                if how == "download":
                    landed += 1
                    log(f"jimaku hunt: movie {ep_id}: new jpn sidecar {cand} (ladder picks it up)")
                else:
                    _jimaku_hunt_record_attempt(rec, now)
                    log(f"jimaku hunt: movie {ep_id}: no jpn found (attempt {rec.get('jimaku_hunt_attempts', 0) + 1})")
            elif how in ("existing", "cache"):
                # found but not downloaded: back off as miss
                _jimaku_hunt_record_attempt(rec, now)
                log(f"jimaku hunt: movie {ep_id}: jpn already present ({how})")
            elif cand:
                log(f"jimaku hunt: movie {ep_id}: jpn already present ({how})")
            # tiny sleep between searches to avoid 429 bursts
            if searched < lc["jimaku_hunt_budget"] and movie_searched < movie_budget:
                time.sleep(2.5)
        else:
            try:
                info = get_episode(cfg, ep_id)
            except Exception as exc:
                log(f"jimaku hunt: get_episode {ep_id} failed: {exc}")
                continue
            ef = info.get("episodeFile") or {}
            if not info.get("hasFile") or not ef.get("path"):
                continue
            media_path = map_path(ef["path"])
            if not os.path.isfile(media_path):
                continue
            series_id = info.get("seriesId") or info.get("sonarrSeriesId")
            key = (ep_id, series_id)
            # DIRECT Jimaku fast path: resolve + list_files for THIS episode
            # without Bazarr's provider lag. A fresh {stem}.jpn.srt landing
            # counts as landed and skips the Bazarr search entirely; any miss
            # falls through to the providers flow below.
            if lc.get("jimaku_direct_enabled"):
                try:
                    dhit, dmeta = jimaku_direct_candidate(
                        cfg,
                        media_path,
                        info.get("seriesTitle") or info.get("title"),
                        info.get("seasonNumber"),
                        info.get("episodeNumber"),
                        cfg.get("TMP_DIR", "/tmp"),
                        ep_id=ep_id,
                        return_meta=True,
                        force=True,
                    )
                except Exception as exc:
                    log(f"WARNING: jimaku hunt: direct path failed for ep {ep_id}: {exc}")
                    dhit, dmeta = None, None
                if dmeta == "hit":
                    searched += 1
                    _BAZARR_JPN_CACHE.pop(key, None)
                    landed += 1
                    log(
                        f"jimaku hunt: ep {ep_id}: direct Jimaku landing "
                        f"{dhit['source_path']} (Bazarr skipped)"
                    )
                    if searched < lc["jimaku_hunt_budget"]:
                        time.sleep(2.5)
                    continue
                if dmeta == "rate_limited":
                    log(
                        f"WARNING: jimaku hunt: aborting remaining hunt due to 429 "
                        f"(direct, ep {ep_id})"
                    )
                    abort_429 = True
                    break
            # Force a fresh attempt even when this episode's one-shot lookup was
            # already consumed earlier in the daemon lifetime (_BAZARR_JPN_TRIED):
            # searching again is exactly what this sweep is for.
            _BAZARR_JPN_TRIED.discard(key)
            try:
                cand, how = bazarr_jpn_candidate(
                    cfg,
                    ep_id,
                    series_id,
                    media_path,
                    cfg.get("TMP_DIR", "/tmp"),
                    return_meta=True,
                    allow_existing=False,
                )
            except Exception as exc:
                log(f"jimaku hunt: ep {ep_id} search failed: {exc}")
                continue
            if how == "rate_limited":
                log(f"WARNING: jimaku hunt: aborting remaining hunt due to 429 (ep {ep_id})")
                abort_429 = True
                break
            if how in ("download", "searched"):
                # Fresh search: drop any stale positive cache so later ladder
                # reads re-scan disk instead of trusting the old path.
                searched += 1
                _BAZARR_JPN_CACHE.pop(key, None)
                if how == "download":
                    landed += 1
                    log(f"jimaku hunt: ep {ep_id}: new jpn sidecar {cand} (ladder picks it up)")
                else:
                    _jimaku_hunt_record_attempt(rec, now)
                    log(f"jimaku hunt: ep {ep_id}: no jpn found (attempt {rec.get('jimaku_hunt_attempts', 0) + 1})")
            elif how in ("existing", "cache"):
                _jimaku_hunt_record_attempt(rec, now)
                log(f"jimaku hunt: ep {ep_id}: jpn already present ({how})")
            elif cand:
                log(f"jimaku hunt: ep {ep_id}: jpn already present ({how})")
            if searched < lc["jimaku_hunt_budget"]:
                time.sleep(2.5)
    log(
        f"jimaku hunt: checked={checked} searched={searched} landed={landed} "
        f"(budget={lc['jimaku_hunt_budget']})"
    )
    return {"checked": checked, "searched": searched, "landed": landed}


