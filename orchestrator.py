def load_records_jsonl(path):
    """Parse a jsonl of dicts, tolerating empty/garbage lines."""
    records = []
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    records.append(json.loads(line))
                except Exception:
                    continue
    return records


def consume_records_jsonl(path):
    """Read a jsonl and remove the consumed records in place.

    Holds an exclusive flock (fcntl) on the single "r+" handle around the
    read/truncate/write, so a producer appending under the same flock
    protocol is serialized: any bytes appended after our last readline are
    rewritten as the new file tail — the consumed prefix is gone, concurrent
    records survive, and no record is processed twice or lost."""
    records = []
    if os.path.exists(path):
        with open(path, "r+", encoding="utf-8") as fh:
            fcntl.flock(fh, fcntl.LOCK_EX)
            try:
                while True:
                    line = fh.readline()
                    if not line:
                        break
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        records.append(json.loads(line))
                    except Exception:
                        continue
                tail = fh.read()
                fh.seek(0)
                fh.truncate(0)
                fh.write(tail)
                fh.flush()
            finally:
                fcntl.flock(fh, fcntl.LOCK_UN)
    return records


def rewrite_jsonl(path, records):
    """Atomic rewrite of a jsonl file (temp file + os.replace)."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        for rec in records:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
    os.replace(tmp, path)


