_SUB_TITLE_SKIP = ("commentary", "description")
_TDARR_MAX_CONCURRENT = 6
# Cap concurrent tdarr-webhook extractions: unbounded ffmpeg demuxes of
# multi-GB files over NFS saturate the link (28/289 timed out at 900s).
_TDARR_SEM = threading.BoundedSemaphore(_TDARR_MAX_CONCURRENT)


def _subtitle_streams(path):
    """All subtitle streams with mkvmerge statistics tags (NUMBER_OF_FRAMES,
    a packet-count proxy present on this library's muxes) and disposition.
    No -count_packets: that forces ffprobe to scan the whole file and times
    out over NFS on large muxes. Header-only read, fast. Raises on ffprobe
    failure."""
    p = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "s",
            "-show_entries",
            "stream=index,codec_type,codec_name:stream_disposition=default,forced,hearing_impaired:stream_tags=language,title,NUMBER_OF_FRAMES",
            "-of",
            "json",
            path,
        ],
        capture_output=True,
        text=True,
        timeout=120,
    )
    if p.returncode != 0:
        raise RuntimeError(f"ffprobe failed: {p.stderr.strip()}")
    return json.loads(p.stdout).get("streams", [])


def _pick_best_subtitle(streams, lang):
    """Best ASS/SSA stream for a language, skipping tracks whose title
    contains 'commentary'/'description' (drpeppershaker convention). Primary
    score is the mkvmerge NUMBER_OF_FRAMES statistics tag (no whole-file
    read); if every candidate lacks it, fall back to disposition order:
    non-forced, then not hearing_impaired, then lower index. Returns the
    stream dict or None."""
    cands = []
    for s in streams:
        tags = s.get("tags") or {}
        if s.get("codec_type") != "subtitle":
            continue
        if s.get("codec_name") not in ("ass", "ssa"):
            continue
        if tags.get("language") != lang:
            continue
        title = (tags.get("title") or "").lower()
        if any(k in title for k in _SUB_TITLE_SKIP):
            continue
        cands.append(s)
    if not cands:
        return None
    scored = []
    for s in cands:
        try:
            frames = int((s.get("tags") or {}).get("NUMBER_OF_FRAMES") or 0)
        except (TypeError, ValueError):
            frames = 0
        scored.append((frames, s))
    if any(f > 0 for f, _ in scored):
        return max(scored, key=lambda fs: fs[0])[1]
    return min(
        cands,
        key=lambda s: (
            int((s.get("disposition") or {}).get("forced") or 0),
            int((s.get("disposition") or {}).get("hearing_impaired") or 0),
            s["index"],
        ),
    )


def _sidecar_unchanged(stem, lang, media_path, audio_id):
    """Webhook dedup: True when re-extraction for (stem, lang) is pointless
    because nothing changed since the last successful extraction — the
    registry row exists, its audio_id matches the CURRENT video's audio
    signature (same file, not a Sonarr upgrade), the on-disk sidecar still
    exists, and its content hash still matches the row's source_hash (not
    clobbered by Bazarr or another writer). Only re-extract when any check
    fails (new file, upgraded video, clobbered sidecar) — which also
    AUTO-HEALS a Bazarr-clobbered sidecar on the next Tdarr event."""
    row = registry_get(stem, lang)
    if not row or not row.get("audio_id") or not row.get("source_hash"):
        return False
    if row["audio_id"] != audio_id:
        return False
    sidecar = f"{stem}.{lang}.srt"
    try:
        return os.path.isfile(sidecar) and file_sha256(sidecar) == row["source_hash"]
    except OSError:
        return False


def extract_subtitle_sidecars(container_path, tdarr_id=""):
    """Background task for POST /tdarr-webhook: pull the single best ASS/SSA
    subtitle stream per language (jpn/eng, scored by mkvmerge NUMBER_OF_FRAMES
    with a disposition fallback, skipping commentary/description titles) out
    of the mux and write deterministic {stem}.{lang}.srt sidecars next to the
    video. Extracts with the exact stream index (-map 0:<index>, never a
    language matcher), writes to {stem}.{lang}.srt.tmp and os.replace()s on
    success so a failed run never leaves a 0-byte file or clobbers a good
    sidecar. Every written sidecar is registered in the provenance registry
    as (stem, lang) source_kind 'embedded' with the video's audio_id and the
    sidecar's content hash. A Tdarr restart/library rescan re-fires this
    webhook for every file, so each lang whose registry row is unchanged
    (audio_id + content hash match) is skipped entirely — the rescan storm
    costs a cheap header-only audio probe, never an ffmpeg job. Concurrent
    extractions are capped by _TDARR_SEM so each demux keeps NFS bandwidth.
    Defensive: missing file, no matching streams, or ffmpeg failure -> log
    and return; never raises. Wakes the main loop on success."""
    tmp_paths = []
    try:
        media_path = map_path(container_path)
        if not os.path.isfile(media_path):
            log(
                f"tdarr-webhook: file missing on NFS: {media_path} (id={tdarr_id})"
            )
            return
        stem = os.path.splitext(media_path)[0]
        try:
            cur_audio = audio_stream_signature(probe_audio(media_path))
        except Exception as exc:
            log(f"tdarr-webhook: audio probe failed for {media_path}: {exc}")
            cur_audio = ""
        if all(
            _sidecar_unchanged(stem, lang, media_path, cur_audio)
            for lang in ("jpn", "eng")
        ):
            log(f"webhook: {os.path.basename(media_path)} jpn/eng unchanged, skip")
            return
        with _TDARR_SEM:
            try:
                streams = _subtitle_streams(media_path)
            except Exception as exc:
                log(f"tdarr-webhook: ffprobe failed for {media_path}: {exc}")
                return
            extracted = []
            for lang in ("jpn", "eng"):
                if _sidecar_unchanged(stem, lang, media_path, cur_audio):
                    log(f"webhook: {os.path.basename(media_path)} {lang} unchanged, skip")
                    continue
                best = _pick_best_subtitle(streams, lang)
                if best is None:
                    log(
                        f"tdarr-webhook: no ASS/SSA '{lang}' subtitle stream in {media_path}"
                    )
                    continue
                index = best["index"]
                out_path = f"{stem}.{lang}.srt"
                tmp_path = out_path + ".tmp"
                tmp_paths.append(tmp_path)
                pp = subprocess.run(
                    [
                        "ffmpeg",
                        "-nostdin",
                        "-v",
                        "error",
                        "-y",
                        "-i",
                        media_path,
                        "-map",
                        f"0:{index}",
                        "-c:s",
                        "srt",
                        "-f",
                        "srt",
                        tmp_path,
                    ],
                    capture_output=True,
                    text=True,
                    timeout=1800,
                )
                if (
                    pp.returncode == 0
                    and os.path.isfile(tmp_path)
                    and os.path.getsize(tmp_path) > 0
                ):
                    os.replace(tmp_path, out_path)
                    extracted.append(out_path)
                    registry_upsert(
                        stem,
                        lang,
                        "embedded",
                        source_path=out_path,
                        source_hash=file_sha256(out_path),
                        source_kind="embedded",
                        audio_id=cur_audio,
                    )
                else:
                    log(
                        f"tdarr-webhook: ffmpeg extract [{lang}] failed for {media_path}: {pp.stderr.strip()}"
                    )
                    try:
                        os.remove(tmp_path)
                    except OSError:
                        pass
            if extracted:
                log(
                    f"tdarr-webhook: extracted {len(extracted)} sidecar(s) for "
                    f"{os.path.basename(media_path)}: {[os.path.basename(x) for x in extracted]}"
                )
                WAKE_EVENT.set()
    except Exception as exc:
        for tmp_path in tmp_paths:
            try:
                os.remove(tmp_path)
            except OSError:
                pass
        log(f"tdarr-webhook: extraction failed for {container_path}: {exc}")


