def recover_fileless_movies(cfg=None):
    """Recovery sweep for movies marked done without a target-lang sidecar
    on disk (Bazarr's async upload crashes on NULL profileId, so the file
    never lands but the pipeline trusted the 204). For each movie missing ANY
    target-lang {stem}.{lang}.srt: clear its registry rows and matching
    state rows so the sweep re-selects it. Movies whose target sidecars all
    exist are skipped; series rows and exclusions are untouched.

    Returns {"cleared": {movie_id: [langs]}, "skipped": n, "fileless": n}."""
    if cfg is None:
        cfg = load_config()
    target_langs = cfg.get("TARGET_LANGS") or []
    try:
        movies = get_movies(cfg)
    except Exception as exc:
        log(f"recovery: movies fetch failed: {exc}")
        return {"cleared": {}, "skipped": 0, "fileless": 0}
    cleared = {}
    skipped = 0
    fileless = 0
    for m in movies.get("data") or []:
        rid = m.get("radarrId")
        if not isinstance(rid, int):
            continue
        p = m.get("path") or ""
        if not p:
            continue
        media_path = map_path(p)
        stem = os.path.splitext(media_path)[0]
        missing = [
            lang for lang in target_langs if not os.path.isfile(f"{stem}.{lang}.srt")
        ]
        if not missing:
            skipped += 1
            continue
        fileless += 1
        title = m.get("title") or "?"
        for lang in missing:
            registry_delete(ep_id=rid, lang=lang)
            registry_delete(stem=stem, lang=lang)
            _clear_movie_state(rid, lang)
            log(
                f"recovery: cleared registry+state for movie {rid} {title} "
                f"[{lang}] (file missing)"
            )
        cleared[rid] = missing
    log(f"recovery: {fileless} fileless movie(s) cleared, {skipped} skipped (have files)")
    return {"cleared": cleared, "skipped": skipped, "fileless": fileless}


def consume_actions(cfg):
    """Process pending actions.jsonl records once per pass; consumed records
    removed in place (tail-preserving: records appended mid-pass survive).

    schema (dashboard control_api_v2): {"ts", "type": "retry"|"skip"|"delete",
    "episode_id": int, "language": null|<code>, "source", "note"} —
    "action" is accepted as an alias for "type", and "language" limits retry
    to specific languages (null = the whole episode).

    - skip:   episode excluded from this pass's candidates
    - retry:  state entries cleared AND the episode's subtitle files removed
              (same _delete_episode_subtitles as delete): Bazarr wanted only
              lists episodes with MISSING subtitles, so clearing state alone
              would never reprocess an episode whose .srt is on disk
              (dashboard Retry would be dead); with the file gone the episode
              re-enters Bazarr wanted and is regenerated. "language" limits
              the state clearing AND the subtitle-file deletion to matching
              languages (null = whole episode).
    - delete: NAS + TMP SRT files removed, done state cleared -> regenerates,
              then Jellyfin refresh so the removed subtitle is dropped.
              "language" scopes the file deletion and state clearing to
              matching languages (null = whole episode), like retry.
    Returns the set of episode ids to exclude this pass (skips)."""
    records = consume_records_jsonl(ACTIONS_FILE)
    if not records:
        return set()
    skip_ids, retry_ids, delete_ids = set(), set(), set()
    retry_langs = {}
    delete_langs = {}
    retry_kinds = {}
    delete_kinds = {}
    for rec in records:
        eid = rec.get("episode_id")
        if not isinstance(eid, int):
            continue
        kind = rec.get("kind") or "series"
        action = rec.get("type") or rec.get("action") or ""
        if action == "skip":
            skip_ids.add(eid)
        elif action in ("retry", "delete"):
            ids = retry_ids if action == "retry" else delete_ids
            langs = retry_langs if action == "retry" else delete_langs
            kinds = retry_kinds if action == "retry" else delete_kinds
            ids.add(eid)
            kinds.setdefault(eid, set()).add(kind)
            lang = rec.get("language")
            entry = langs.setdefault(eid, set())
            if isinstance(lang, str) and lang:
                entry.add(lang)
            else:
                entry.add(None)  # null language = whole episode
    if retry_ids or delete_ids:
        states = load_state()
        kept = []
        changed = False
        for e in states:
            eid = e.get("sonarrEpisodeId")
            lang = e.get("language")
            e_kind = e.get("kind") or "series"
            drop = False
            if isinstance(eid, int) and eid in retry_ids:
                if e_kind in (retry_kinds.get(eid) or {"series"}):
                    langs = retry_langs.get(eid)
                    drop = not langs or (None in langs) or (lang in langs)
            elif isinstance(eid, int) and eid in delete_ids:
                if e_kind in (delete_kinds.get(eid) or {"series"}):
                    langs = delete_langs.get(eid)
                    drop = not langs or (None in langs) or (lang in langs)
            if drop:
                changed = True
            else:
                kept.append(e)
        if changed:
            rewrite_jsonl(STATE_FILE, kept)
    for eid in sorted(delete_ids):
        kinds = delete_kinds.get(eid) or {"series"}
        langs = delete_langs.get(eid)
        all_langs = not langs or None in langs
        lang_list = None if all_langs else sorted(langs)
        if "series" in kinds:
            deleted = _delete_episode_subtitles(cfg, eid, langs=lang_list)
            log(f"action: delete episode {eid} (removed {len(deleted)} SRTs, state cleared)")
        if "movie" in kinds:
            deleted = _delete_movie_subtitles(cfg, eid, langs=lang_list)
            log(f"action: delete movie {eid} (removed {len(deleted)} SRTs, state cleared)")
        if "series" in kinds:
            media_path, title = "", None
            try:
                info = get_episode(cfg, eid)
                ef = info.get("episodeFile") or {}
                media_path = map_path(ef.get("path", "")) if ef.get("path") else ""
                title = info.get("title") or info.get("Name")
            except Exception:
                pass
            if media_path:
                jellyfin_refresh(cfg, media_path, title)
        if "movie" in kinds:
            try:
                movies = get_movies(cfg)
                m = next(
                    (x for x in (movies.get("data") or []) if x.get("radarrId") == eid),
                    None,
                )
                if m and m.get("path"):
                    jellyfin_refresh(
                        cfg, map_path(m["path"]), m.get("title"), item_type="Movie"
                    )
            except Exception:
                pass
    for eid in sorted(retry_ids):
        kinds = retry_kinds.get(eid) or {"series"}
        langs = retry_langs.get(eid)
        all_langs = not langs or None in langs
        lang_list = None if all_langs else sorted(langs)
        if "series" in kinds:
            deleted = _delete_episode_subtitles(cfg, eid, langs=lang_list)
            log(f"action: retry episode {eid} (state cleared, {len(deleted)} SRTs removed)")
        if "movie" in kinds:
            deleted = _delete_movie_subtitles(cfg, eid, langs=lang_list)
            log(f"action: retry movie {eid} (state cleared, {len(deleted)} SRTs removed)")
    for eid in sorted(skip_ids):
        log(f"action: skip episode {eid} (excluded this pass)")
    return skip_ids


def _bazarr_endpoint(cfg, lang):
    """Dual-Bazarr upload routing: ja -> primary BAZARR_URL (Japanese
    profile); any other lang -> BAZARR_URL_2 (id/en profile) when
    configured, else primary. Returns (base_url, api_key)."""
    if lang == "ja":
        return cfg["BAZARR_URL"].rstrip("/"), cfg["BAZARR_API_KEY"]
    base2 = cfg.get("BAZARR_URL_2")
    if base2:
        return base2.rstrip("/"), cfg.get("BAZARR_API_KEY_2") or ""
    return cfg["BAZARR_URL"].rstrip("/"), cfg["BAZARR_API_KEY"]


def _ensure_sidecar_on_disk(cfg, media_path, lang, srt_bytes, retries=3, delay=2.0):
    """After a Bazarr upload 204, confirm {stem}.{lang}.srt exists on the
    NAS. Bazarr's upload endpoint returns 204 after QUEUEING the job async,
    and the async job can crash (movies: NULL profileId -> TypeError in
    Bazarr upload.py) so the file never lands. Poll for it, then write it
    directly (tmp + os.replace, exactly like the ladder path) if still
    missing. Returns (path, wrote) or (None, False) on persistent failure.
    media_path MUST be the already-mapped NAS path."""
    if not media_path:
        return None, False
    stem = os.path.splitext(media_path)[0]
    target = f"{stem}.{lang}.srt"
    for i in range(retries):
        if os.path.isfile(target):
            return target, False
        if i < retries - 1:
            time.sleep(delay)
    if os.path.isfile(target):
        return target, False
    try:
        tmp = target + ".direct.tmp"
        with open(tmp, "wb") as fh:
            fh.write(srt_bytes)
        os.replace(tmp, target)
        return target, True
    except OSError as exc:
        log(f"upload: direct write failed for {target}: {exc}")
        return None, False


def upload_srt(cfg, series_id, ep_id, lang, srt_bytes, filename="sub.srt", media_path=None):
    """Manual upload via POST /api/episodes/subtitles (verified against live
    Bazarr swagger.json 2026-08-07): query seriesid/episodeid/language/
    forced/hi + multipart file. Movies use POST /api/movies/subtitles
    (radarrid) via upload_srt_movie. Bazarr ignores the uploaded
    filename (subliminal writes {video stem}.{lang alpha2}.srt), and the
    endpoint has no comment/history field, so AI provenance lives only in the
    first SRT cue. After a 204 (Bazarr queues the job async), the on-disk
    sidecar is verified/direct-written via _ensure_sidecar_on_disk when
    media_path is provided; a missing file that cannot be written fails the
    upload (returns None) so the item is NOT marked done."""
    base, key = _bazarr_endpoint(cfg, lang)
    url = base + "/episodes/subtitles"
    params = {
        "seriesid": series_id,
        "episodeid": ep_id,
        "language": lang,
        "forced": "false",
        "hi": "false",
    }
    headers = {"X-API-KEY": key}
    files = {"file": (filename, srt_bytes, "application/x-subrip")}
    last_code = None
    for attempt in range(3):
        try:
            r = requests.post(
                url, params=params, headers=headers, files=files, timeout=120
            )
            last_code = r.status_code
            if r.status_code == 204:
                if media_path is None:
                    log("series upload 204 (no media path to verify; trusting Bazarr)")
                    return 204
                target, wrote = _ensure_sidecar_on_disk(cfg, media_path, lang, srt_bytes)
                if target is None:
                    log(
                        f"series upload 204 + file MISSING -> direct write failed "
                        f"({media_path})"
                    )
                    return None
                log(
                    "series upload 204 + "
                    + ("file MISSING -> direct write" if wrote else "file confirmed")
                    + f" ({target})"
                )
                return 204
            log(
                f"    [upload] HTTP {r.status_code} (attempt {attempt + 1}): {r.text[:200]}"
            )
        except requests.RequestException as exc:
            last_code = None
            log(f"    [upload] network error (attempt {attempt + 1}): {exc}")
        if attempt < 2:
            time.sleep(5 * (attempt + 1))
    return last_code


