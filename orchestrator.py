def notify_hermes(cfg, ep_id, lang, series, tag, exc):
    global _GLOBAL_HELP_LAST
    try:
        url = cfg.get("HERMES_WEBHOOK_URL", "")
        secret = cfg.get("HERMES_WEBHOOK_SECRET", "")
        if not url or not secret:
            return
        now = time.time()
        last = _HELP_COOLDOWN.get((ep_id, lang), 0)
        if now - last < 1800:
            return
        if now - _GLOBAL_HELP_LAST < 600:
            log("help: throttled (global)")
            return
        payload = {
            "event_type": "pipeline_error",
            "episode": f"{tag} {series}",
            "lang": lang,
            "error": str(exc)[:500],
            "log_tail": list(_LOG_RING),
        }
        body = json.dumps(payload).encode()
        ts = str(int(time.time()))
        sig = hmac.new(
            secret.encode(), ts.encode() + b"." + body, hashlib.sha256
        ).hexdigest()
        headers = {
            "X-Webhook-Signature-V2": sig,
            "X-Webhook-Timestamp": ts,
            "Content-Type": "application/json",
        }
        r = requests.post(url, data=body, headers=headers, timeout=10)
        if r.status_code in (200, 202):
            _HELP_COOLDOWN[(ep_id, lang)] = time.time()
            _GLOBAL_HELP_LAST = time.time()
            log(f"help: {tag} {series} [{lang}] notified Hermes")
        else:
            log(f"help: notify failed: HTTP {r.status_code}")
    except Exception as e:
        log(f"help: notify failed: {e}")


def process_after_asr(
    cfg,
    key,
    ep_id,
    lang,
    series,
    tag,
    src,
    t0,
    cues,
    decision,
    info,
    wav_path,
    srt_path,
    prior_cache=None,
    movie_id=None,
):
    global _paused
    try:
        if decision["needs_translate"]:
            t_tr = time.time()
            if not key and not is_local_translate(cfg):
                raise RuntimeError("translate needed but TRANSLATE_API_KEY empty")
            groups = translate_texts(
                cfg,
                cues,
                lang,
                key,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                prior_cache,
                series_title=series,
            )
            if groups is None:
                raise RuntimeError("translation failed")
            cues_out = []
            texts_out = []
            for s, e, t in groups:
                cues_out.append({"start": cues[s]["start"], "end": cues[e - 1]["end"]})
                texts_out.append(t)
            tr_elapsed = time.time() - t_tr
            log(
                f"  {tag} [{src}->{lang}] translate {tr_elapsed:.0f}s, {len(texts_out)} lines"
            )
        else:
            cues_out = cues
            texts_out = [c["text"] for c in cues]

        # ASR-translated output only: merge too-fast translated cues with the
        # following cue so the reading speed stays within max_cps (ladder
        # output never passes through here — it writes at its own call site).
        merged = cps_merge(
            [
                {"start": c["start"], "end": c["end"], "text": t}
                for c, t in zip(cues_out, texts_out)
            ]
        )
        cues_out = [{"start": c["start"], "end": c["end"]} for c in merged]
        texts_out = [c["text"] for c in merged]

        write_srt(cues_out, texts_out, srt_path, header=AI_MARKER)
        with open(srt_path, "rb") as fh:
            srt_bytes = fh.read()
        if movie_id is not None:
            code = upload_srt_movie(
                cfg, movie_id, lang, srt_bytes, filename=os.path.basename(srt_path)
            )
        else:
            code = upload_srt(
                cfg,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                lang,
                srt_bytes,
                filename=os.path.basename(srt_path),
            )
        if code != 204:
            raise RuntimeError(f"upload HTTP {code} (expected 204)")
        ef = info.get("episodeFile") or {}
        if ef.get("path"):
            jellyfin_refresh(
                cfg,
                map_path(ef["path"]),
                info.get("title") or info.get("Name"),
                item_type="Movie" if movie_id is not None else "Episode",
            )
        elapsed = round(time.time() - t0, 1)
        stem = os.path.splitext(map_path((info.get("episodeFile") or {}).get("path", "")))[0] or None
        registry_upsert(stem, lang, "asr", ep_id=ep_id)
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "done",
            "elapsed_s": elapsed,
            "source": "asr",
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        log(f"done: {tag} {series} [{src}->{lang}] in {elapsed}s (upload 204)")
        return "done"
    except Exception as exc:
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "error",
            "elapsed_s": round(time.time() - t0, 1),
            "source": "asr",
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        log(f"fail: {series} [{lang}] {exc}")
        notify_hermes(cfg, ep_id, lang, series, tag, exc)
        halt_on_error(cfg, "process_episode", f"{series} [{lang}] {tag}", exc)
        return "failed"
    finally:
        for f in (wav_path, srt_path):
            try:
                os.remove(f)
            except OSError:
                pass


def process_ladder(
    cfg,
    key,
    ep_id,
    lang,
    series,
    tag,
    source,
    info,
    prior_cache=None,
    movie_id=None,
):
    """Ladder translation: translate from an existing jpn/eng subtitle source
    (SKIP ASR entirely), write {stem}.{lang}.srt next to the video with the AI
    marker cue, register the source in the registry and wake Jellyfin. An eng
    source satisfying the en target is adopted verbatim (no marker: it is not
    AI-generated text, but ownership is still registry-tracked). Returns
    "done" or "failed". movie_id (radarr track): uploads via the movies
    endpoint, state rows carry kind "movie", and the Jellyfin refresh searches
    Movie items; None keeps series behavior."""
    t0 = time.time()
    kind = source["kind"]
    try:
        media_path = map_path((info.get("episodeFile") or {}).get("path", ""))
        if not media_path or not os.path.isfile(media_path):
            raise RuntimeError(f"media file missing: {media_path}")
        cues = source["cues"] or []
        if not cues:
            raise RuntimeError("ladder source produced no cues")
        srt_path = os.path.splitext(media_path)[0] + f".{lang}.srt"
        needs_translate = not ((kind == "eng" and lang == "en") or (kind in ("jpn", "asr") and lang == "ja"))
        if needs_translate:
            if not key and not is_local_translate(cfg):
                raise RuntimeError("translate needed but TRANSLATE_API_KEY empty")
            t_tr = time.time()
            groups = translate_texts(
                cfg,
                cues,
                lang,
                key,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                prior_cache,
                series_title=series,
                skip_guard=(kind == "eng"),
            )
            if groups is None:
                raise RuntimeError("translation failed")
            cues_out = []
            texts_out = []
            for s, e, t in groups:
                cues_out.append({"start": cues[s]["start"], "end": cues[e - 1]["end"]})
                texts_out.append(t)
            log(
                f"  {tag} [{kind}->{lang}] translate {time.time() - t_tr:.0f}s, {len(texts_out)} lines"
            )
            header = AI_MARKER
        else:
            cues_out = cues
            texts_out = [c["text"] for c in cues]
            header = None
        tmp = srt_path + ".ladder.tmp"
        write_srt(cues_out, texts_out, tmp, header=header)
        os.replace(tmp, srt_path)
        with open(srt_path, "rb") as fh:
            srt_bytes = fh.read()
        if movie_id is not None:
            code = upload_srt_movie(
                cfg, movie_id, lang, srt_bytes, filename=os.path.basename(srt_path)
            )
        else:
            code = upload_srt(
                cfg,
                info.get("seriesId") or info.get("sonarrSeriesId"),
                ep_id,
                lang,
                srt_bytes,
                filename=os.path.basename(srt_path),
            )
        if code != 204:
            raise RuntimeError(f"upload HTTP {code} (expected 204)")
        stem = os.path.splitext(media_path)[0]
        # Registry the produced {stem}.{lang}.srt with the SOURCE's
        # provenance: when the ladder used an on-disk sidecar that still
        # matches its own registry row (webhook embedded extraction, hash
        # untouched), PRESERVE the row's source_kind instead of flipping it
        # to "external" — a webhook-extracted sidecar is aligned by
        # construction even when consumed from disk. "external" only when
        # the sidecar was clobbered (hash mismatch) or never registered.
        # A tmp extraction is embedded by construction and never clobbers
        # the on-disk sidecar's own row.
        src_row = registry_get(stem, kind)
        if source.get("tmp"):
            source_kind = "embedded"
        elif (
            src_row
            and src_row.get("source_hash")
            and src_row["source_hash"] == source["source_hash"]
        ):
            source_kind = src_row.get("source_kind") or "external"
        else:
            source_kind = "external"
        registry_upsert(
            stem,
            lang,
            kind,
            source_path=source["source_path"],
            source_hash=source["source_hash"],
            source_kind=source_kind,
            ep_id=ep_id,
            retimed=source.get("align_stats", {}).get("method"),
            matched_frac=source.get("align_stats", {}).get("matched_frac"),
        )
        elapsed = round(time.time() - t0, 1)
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "done",
            "elapsed_s": elapsed,
            "source": kind,
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        jellyfin_refresh(
            cfg,
            media_path,
            info.get("title") or info.get("Name"),
            item_type="Movie" if movie_id is not None else "Episode",
        )
        log(f"done: {tag} {series} [{kind}->{lang}] in {elapsed}s (upload 204, ladder)")
        return "done"
    except Exception as exc:
        st_entry = {
            "sonarrEpisodeId": ep_id,
            "language": lang,
            "status": "error",
            "elapsed_s": round(time.time() - t0, 1),
            "source": kind,
        }
        if movie_id is not None:
            st_entry["kind"] = "movie"
        append_state(st_entry)
        log(f"fail: {series} [{lang}] {exc}")
        notify_hermes(cfg, ep_id, lang, series, tag, exc)
        halt_on_error(cfg, "process_ladder", f"{series} [{lang}] {tag}", exc)
        return "failed"
    finally:
        if source.get("tmp") and source.get("source_path"):
            try:
                os.remove(source["source_path"])
            except OSError:
                pass
        if source.get("align_tmp"):
            _silent_remove(source["align_tmp"])


def run_upgrades(cfg, key, prior_cache=None):
    """Auto-upgrade pass: AI-owned subs produced from ASR/eng get re-translated
    from a better jpn source when one appears. Guards: only AI-owned subs
    (registry authoritative, marker fallback), refine-history skip
    (LADDER_SKIP_REFINED), source-hash dedup, per-episode cooldown +
    per-pass upgrade budget (LADDER_UPGRADE_BUDGET). Returns
    {"upgraded": n, "checked": n}."""
    lc = _ladder_cfg(cfg)
    if lc["upgrade_budget"] <= 0:
        return {"upgraded": 0, "checked": 0}
    registry = load_registry()
    refined = load_refined_set() if lc["skip_refined"] else set()
    now = datetime.now(timezone.utc)
    rows = sorted(
        (
            rec
            for rec in registry.values()
            if rec.get("source") in ("asr", "eng")
        ),
        key=lambda r: r.get("updated_ts") or r.get("created_ts") or "",
    )
    upgraded = 0
    checked = 0
    for rec in rows:
        ep_id = rec.get("episode_id")
        lang = rec.get("lang")
        if upgraded >= lc["upgrade_budget"]:
            break
        if (ep_id, lang) in refined:
            log(f"upgrade: skip {ep_id} [{lang}] refined (refine_history)")
            continue
        updated = rec.get("updated_ts") or rec.get("created_ts") or ""
        try:
            age_h = (
                now - datetime.fromisoformat(updated.replace("Z", "+00:00"))
            ).total_seconds() / 3600
        except Exception:
            age_h = None  # unknown age: eligible
        if age_h is not None and age_h < lc["cooldown_h"]:
            continue
        checked += 1
        try:
            info = get_episode(cfg, ep_id)
        except Exception as exc:
            log(f"upgrade: get_episode {ep_id} failed: {exc}")
            continue
        ef = info.get("episodeFile") or {}
        if not info.get("hasFile") or not ef.get("path"):
            continue
        media_path = map_path(ef["path"])
        if not os.path.isfile(media_path):
            continue
        if not sub_is_ai_owned(registry, ep_id, lang, media_path):
            continue  # foreign sub on disk: never touched
        ladder = detect_ladder_source(
            cfg,
            media_path,
            lang,
            cfg.get("TMP_DIR", "/tmp"),
            ep_id,
            info.get("seriesId") or info.get("sonarrSeriesId"),
        )
        if ladder["kind"] != "jpn":
            continue
        if (
            rec.get("source_hash")
            and ladder["source_hash"]
            and rec["source_hash"] == ladder["source_hash"]
        ):
            continue  # same source already translated
        season = info.get("seasonNumber", "?")
        ep_num = info.get("episodeNumber", "?")
        tag = (
            f"S{season:02d}E{ep_num:02d}"
            if isinstance(season, int) and isinstance(ep_num, int)
            else f"S{season}E{ep_num}"
        )
        series = info.get("seriesTitle") or info.get("title") or "?"
        status = process_ladder(
            cfg, key, ep_id, lang, series, tag, ladder, info, prior_cache=prior_cache
        )
        if status == "done":
            upgraded += 1
    if checked or upgraded:
        log(
            f"upgrade pass: checked={checked} upgraded={upgraded} "
            f"(budget={lc['upgrade_budget']}, cooldown_h={lc['cooldown_h']})"
        )
    return {"upgraded": upgraded, "checked": checked}


