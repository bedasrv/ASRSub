# ---------- SRT ----------


def parse_srt(text):
    cues = []
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = [l.strip() for l in block.splitlines() if l.strip()]
        if not lines:
            continue
        ts_idx = next((i for i, l in enumerate(lines) if "-->" in l), None)
        if ts_idx is None:
            continue
        m = re.match(
            r"(\d{2}:\d{2}:\d{2},\d{3})\s*-->\s*(\d{2}:\d{2}:\d{2},\d{3})",
            lines[ts_idx],
        )
        if not m:
            continue
        body = " ".join(lines[ts_idx + 1 :]).strip()
        if not body:
            continue
        cues.append({"start": m.group(1), "end": m.group(2), "text": body})
    return cues


_ASS_OVERRIDE_RE = re.compile(r"\{[^}]*\}")
_ASS_HTML_RE = re.compile(r"<[^>]+>")


def clean_ass_text(text):
    """Strip ASS/SSA styling from a subtitle cue's body: {\\an8} override
    blocks and <font ...> HTML tags (sidecars extracted by the tdarr webhook
    carry both). \\N / \\n become real line breaks; blank lines collapse."""
    text = text.replace("\\N", "\n").replace("\\n", "\n")
    text = _ASS_OVERRIDE_RE.sub("", text)
    text = _ASS_HTML_RE.sub("", text)
    return "\n".join(l.strip() for l in text.splitlines() if l.strip())


def srt_ts_ms(v):
    """SRT timestamp (string or number-of-ms) -> float ms, or None."""
    if isinstance(v, (int, float)):
        return float(v)
    m = re.match(r"(\d+):(\d+):(\d+)[,.](\d+)", str(v))
    if m:
        h, mi, s, ms = m.groups()
        return int(h) * 3600000 + int(mi) * 60000 + int(s) * 1000 + int(ms)
    return None


def media_duration_s(path):
    """Container duration in seconds via ffprobe, or None on failure."""
    p = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "json",
            path,
        ],
        capture_output=True,
        text=True,
        timeout=120,
    )
    if p.returncode != 0:
        return None
    try:
        return float(json.loads(p.stdout)["format"]["duration"])
    except (ValueError, KeyError, TypeError):
        return None


def file_sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _fmt_ms(ms):
    ms = int(round(ms))
    h, rem = divmod(ms, 3600000)
    m, rem = divmod(rem, 60000)
    s, msr = divmod(rem, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{msr:03d}"


def _fmt_ts(v):
    if isinstance(v, (int, float)):
        return _fmt_ms(v)
    return v


def write_srt(cues, texts, out_path, header=None):
    """Write SRT. header (AI marker) becomes a REAL first cue at 00:00:00,000
    -> 00:00:01,500 (config AI_MARKER_CUE, default on) — bare text lines are
    dropped by players until a timestamped cue is seen. If the first dialogue
    cue starts before 2s, the marker cue ends just before it."""
    with open(out_path, "w", encoding="utf-8") as fh:
        idx = 1
        if header and AI_MARKER_CUE:
            first_start = None
            for cue in cues:
                if cue.get("text", "").strip():
                    first_start = cue.get("start")
                    break
            marker_end = AI_MARKER_CUE_MS
            if first_start is not None:
                first_ms = srt_ts_ms(first_start)
                if first_ms is not None and first_ms < 2000:
                    marker_end = max(0, int(first_ms) - 1)
            fh.write(
                f"{idx}\n00:00:00,000 --> {_fmt_ms(marker_end)}\n{header}\n\n"
            )
            idx = 2
        elif header:
            fh.write(header + "\n\n")
        for cue, text in zip(cues, texts):
            fh.write(
                f"{idx}\n{_fmt_ts(cue['start'])} --> {_fmt_ts(cue['end'])}\n{text}\n\n"
            )
            idx += 1


