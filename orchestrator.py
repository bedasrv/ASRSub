def _parse_numbered_response(raw):
    if not raw:
        return None
    parsed = {}
    for line in raw.splitlines():
        m = re.match(r"^(\d+)[.．…]?\s*(.+)$", line.strip())
        if m:
            parsed[int(m.group(1))] = m.group(2).strip()
    return parsed


def _parse_local_response(raw, max_count=None):
    """Parse a JSON array into a contiguous 1-based response mapping.

    Partial arrays are valid for merge-aware tail completion; arrays longer than
    the requested input are rejected before they can overrun cue assembly.
    """
    parsed = extract_json_array(raw)
    if not parsed or (max_count is not None and max_count < 1):
        return None
    if max_count is not None:
        parsed = parsed[:max_count]
    return {i + 1: text.strip() for i, text in enumerate(parsed)}


_NON_LATIN_LETTER_RE = re.compile(
    "[\u0370-\u03FF\u0400-\u04FF\u0500-\u052F\u0590-\u05FF\u0600-\u06FF"
    "\u0900-\u097F\u0E00-\u0E7F\u3040-\u309F\u30A0-\u30FF\u3400-\u4DBF"
    "\u4E00-\u9FFF\uAC00-\uD7AF]"
)
_CJK_KANA_RE = re.compile(r"[\u3040-\u30FF\u3400-\u4DBF\u4E00-\u9FFF]")


def _wrong_script(line, target_lang):
    """True when a translated line contains characters of a script the
    target language must not contain. Latin targets (Indonesian, English)
    reject any non-Latin letter (Cyrillic/Greek/Arabic/CJK/Kana/Hangul/
    Thai/...). Japanese rejects only lines that are entirely alien — no CJK
    and no Latin letters (e.g. Cyrillic-only); mixed CJK+Latin is normal
    Japanese output."""
    if not line:
        return False
    if target_lang == "Japanese":
        has_cjk = bool(_CJK_KANA_RE.search(line))
        has_latin = bool(re.search(r"[A-Za-z]", line))
        return not has_cjk and not has_latin and bool(_NON_LATIN_LETTER_RE.search(line))
    return bool(_NON_LATIN_LETTER_RE.search(line))


def sanitize_lines(lines, max_repeat=10):
    """Collapse runs of >max_repeat identical chars to max_repeat + ellipsis
    (anime scream lines otherwise trigger repetition collapse in small models)."""
    out = []
    for s in lines:
        if not s:
            out.append(s)
            continue
        parts = []
        i = 0
        while i < len(s):
            j = i
            while j < len(s) and s[j] == s[i]:
                j += 1
            run = j - i
            if run > max_repeat:
                parts.append(s[i] * max_repeat + "…")
            else:
                parts.append(s[i:j])
            i = j
        out.append("".join(parts))
    return out


def guard_foreign_lines(lines, sdh_placeholders=None):
    """Replace foreign-script lines (Chinese w/o kana, mostly-latin English) with an
    SDH placeholder (default （歌詞）) so the model does not echo the whole chunk.
    Returns (guarded_lines, [(original_index, original_text), ...]) for swap-back."""
    sdh = list(sdh_placeholders) if sdh_placeholders else list(DEFAULT_SDH_PLACEHOLDERS)
    out, foreign = [], []
    for i, l in enumerate(lines):
        latin_chars = LATIN_RE.findall(l)
        latin_ratio = len(latin_chars) / max(len(l), 1)
        if (HANZI_RE.search(l) and not KANA_RE.search(l)) or (
            latin_ratio > 0.5 and not KANA_RE.search(l)
        ):
            foreign.append((i, l))
            out.append(sdh[i % len(sdh)])
        else:
            out.append(l)
    return out, foreign


def _gemma_prompt(chunk, lang_name, refs=None, context_lines=None, emotions=None):
    """Build the generic Gemma system prompt and JSON user payload.

    refs is the stable KNOWLEDGE block for the episode (already rendered by
    pipeline.glossary.knowledge_block / knowledge_block_for_cues). It is
    injected verbatim as background knowledge and reused identically across
    all chunks/batches of the episode for llama-server KV/prefix-cache reuse.
    """
    parts = [
        "You are a professional subtitle translator.",
        f"Target language: {lang_name}.",
        "Translate every input line naturally and preserve the input order.",
        "Return ONLY a JSON array of translated strings; no prose or markdown.",
        "Keep names, honorifics, meaning, and subtitle brevity; each line <=42 characters.",
    ]
    if refs:
        parts.append(refs)
    if context_lines:
        capped = context_lines[:TRANSLATE_CONTEXT_LINES]
        parts.append("Prior translated context:\n" + "\n".join(capped))
    if emotions and any(emotions):
        hints = ", ".join(f"{i + 1}: {emotion}" for i, emotion in enumerate(emotions) if emotion)
        if hints:
            parts.append("Optional emotion hints by source-line number: " + hints)
    system = "\n\n".join(parts)
    user = json.dumps(
        {"source_language": "Japanese", "target_language": lang_name, "lines": chunk},
        ensure_ascii=False,
    )
    return system, user


def _local_chunk(cfg, chunk, lang_name, key, refs=None, context_lines=None,
                 emotions=None):
    """One local-model chat call using the Gemma JSON contract."""
    n = len(chunk)
    system, user = _gemma_prompt(chunk, lang_name, refs=refs,
                                  context_lines=context_lines, emotions=emotions)
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]
    raw = post_chat(cfg, messages, cfg.get("TRANSLATE_MODEL") or TRANSLATE_MODEL, key, local=True)
    if raw is None:
        return None
    return _parse_local_response(raw, n)


def _attempt_chunk(cfg, chunk, lang_name, key, echo_probe=11, refs=None,
                   context_lines=None, emotions=None):
    """Up to 3 attempts per chunk; corrective retry on echo OR wrong-script
    output (target-script guard). Echo probe is skipped for Japanese targets
    (correct output always contains kana/kanji). Returns clean parsed dict or
    None (all attempts empty/echo/wrong-script/network-fail)."""
    n = len(chunk)
    for _ in range(3):
        parsed = _local_chunk(cfg, chunk, lang_name, key, refs=refs,
                              context_lines=context_lines, emotions=emotions)
        if not parsed:
            continue
        if any(_wrong_script(t, lang_name) for t in parsed.values()):
            continue
        if lang_name == "Japanese":
            return parsed
        echo = False
        for k in range(1, min(echo_probe, n) + 1):
            t = parsed.get(k)
            if t and re.search(r"[\u3040-\u30ff\u3400-\u9fff]", t):
                echo = True
                break
        if not echo:
            return parsed
    return None


def _complete_tail(cfg, tail_lines, m, lang_name, key, refs=None,
                   context_lines=None, emotions=None):
    """Complete a chunk's missing tail: translate source lines m..n-1
    (numbered m+1..n in the prompt), remap keys to absolute m+i. Returns
    merged dict for the full chunk (keys 1..n) or None after 3 attempts."""
    n = m + len(tail_lines)
    for _ in range(3):
        system, user = _gemma_prompt(
            tail_lines, lang_name, refs=refs, context_lines=context_lines,
            emotions=(emotions[m:] if emotions else None),
        )
        messages = [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ]
        raw = post_chat(cfg, messages, cfg.get("TRANSLATE_MODEL") or TRANSLATE_MODEL, key, local=True)
        if raw is None:
            continue
        parsed = _parse_local_response(raw, len(tail_lines))
        if not parsed:
            continue
        if any(_wrong_script(t, lang_name) for t in parsed.values()):
            continue
        echo = False
        for rel in range(1, min(5, n - m) + 1):
            t = parsed.get(rel)
            if t and re.search(r"[\u3040-\u30ff\u3400-\u9fff]", t):
                echo = True
                break
        if echo:
            continue
        return {m + i: text for i, text in parsed.items()}
    return None


def _translate_merge_aware(cfg, lines, lang_name, key, refs=None,
                           context_lines=None, emotions=None):
    """Translate, tolerating Gemma merging consecutive short lines. Returns
    list of (cue_start_idx, cue_end_idx_exclusive, text)."""
    groups = []
    cs = TRANSLATE_CHUNK
    for start in range(0, len(lines), cs):
        chunk = lines[start : start + cs]
        n = len(chunk)
        parsed = _attempt_chunk(cfg, chunk, lang_name, key, refs=refs,
                                context_lines=context_lines,
                                emotions=(emotions[start:start + cs] if emotions else None))
        if parsed is None:
            for j in range(n):
                gi = start + j
                p = _attempt_chunk(cfg, [chunk[j]], lang_name, key, echo_probe=1,
                                   refs=refs, context_lines=context_lines,
                                   emotions=([emotions[gi]] if emotions and emotions[gi] else None))
                text = re.sub(r"^>\s*", "", (p or {}).get(1, ""))
                groups.append((gi, gi + 1, text))
            continue
        entries = sorted(parsed.items())
        m = len(entries)
        if m == n:
            for k, t in entries:
                if k < 1 or k > n:
                    continue
                groups.append((start + k - 1, start + k, re.sub(r"^>\s*", "", t)))
            continue
        entries_dict = dict(entries)
        tail_lines = chunk[m:n]
        merged = None
        if tail_lines:
            completion = _complete_tail(cfg, tail_lines, m, lang_name, key,
                                        refs=refs, context_lines=context_lines,
                                        emotions=emotions)
            if completion:
                merged = {**entries_dict, **completion}
        if merged:
            for k, t in sorted(merged.items()):
                if k > n:
                    continue
                groups.append((start + k - 1, start + k, re.sub(r"^>\s*", "", t)))
        else:
            for k, t in entries:
                if k > n:
                    continue
                gi = start + k - 1
                groups.append((gi, gi + 1, re.sub(r"^>\s*", "", t)))
            for k in range(m + 1, n + 1):
                gi = start + k - 1
                p = _attempt_chunk(cfg, [chunk[k - 1]], lang_name, key, echo_probe=1,
                                   refs=refs, context_lines=context_lines,
                                   emotions=([emotions[gi]] if emotions and emotions[gi] else None))
                text = re.sub(r"^>\s*", "", (p or {}).get(1, ""))
                groups.append((gi, gi + 1, text))
    return groups


def chat_translate_batch(cfg, lines, target_lang, key, context_lines=None, series_title=None, skip_guard=False, emotions=None):
    lines = sanitize_lines(lines)
    if is_local_translate(cfg):
        # local Gemma path: generic JSON contract with KNOWLEDGE injection and
        # optional tone hints (emotions, one per line). Foreign lines become
        # SDH placeholders (kept in output, not swapped back) — skipped when
        # the SOURCE is already eng/latin (skip_guard) so it can be translated.
        # KNOWLEDGE block: built ONCE per episode pass (stable prefix for
        # llama-server KV/prefix-cache reuse across all chunks) via cast
        # resolution — scan full cue text case-insensitively for any entry
        # surface form (ja, en, aliases); inject only matched entries, fallback
        # to full list when <3 match (ASR-garbling fallback). Cached in the
        # local variable `knowledge` for this episode pass.
        sdh = cfg.get("SDH_PLACEHOLDERS") or DEFAULT_SDH_PLACEHOLDERS
        # scan original sanitized lines before foreign-guard for cast resolution
        knowledge = ""
        if series_title:
            knowledge = pipeline_glossary.knowledge_block_for_cues(series_title, lines)
            if knowledge:
                log(f"    [translate] knowledge block for series: {len(knowledge)} chars")
        if not skip_guard:
            lines, _foreign = guard_foreign_lines(lines, sdh)
        lang_name = LANG_NAMES.get(target_lang, target_lang)
        return _translate_merge_aware(cfg, lines, lang_name, key, refs=knowledge,
                                      context_lines=context_lines, emotions=emotions)
    models = [cfg.get("TRANSLATE_MODEL") or TRANSLATE_MODEL] + [
        m for m in MODEL_FALLBACKS if m != cfg.get("TRANSLATE_MODEL")
    ]
    system = TRANSLATE_PROMPT.format(target_language=target_lang)
    if context_lines:
        system += (
            "\n\nUse these previously translated lines from earlier episodes for "
            "consistent names, terms, and style:\n"
            + "\n".join(f"REF: {l}" for l in context_lines)
        )
    user = json.dumps(
        {"target_language": target_lang, "lines": lines}, ensure_ascii=False
    )
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]
    for _ in range(2):  # one corrective retry on parse failure
        raw = None
        for model in models:
            content = post_chat(cfg, messages, model, key)
            if content is None:
                continue  # 404 -> next model, or network dead -> try next model too
            raw = content
            break
        if raw is None:
            log("    [translate] all models/attempts failed (network or 404)")
            return None
        parsed = extract_json_array(raw)
        if parsed is not None and len(parsed) == len(lines):
            return parsed
        messages.append({"role": "assistant", "content": raw})
        messages.append(
            {
                "role": "user",
                "content": (
                    f"Your previous output was not a JSON array with exactly {len(lines)} "
                    'strings. Output ONLY the JSON array, e.g. ["...", "..."], same count '
                    "and order as the input."
                ),
            }
        )
    log("    [translate] unparseable / count mismatch after retry")
    return None


def translate_texts(
    cfg,
    cues,
    target_lang,
    key,
    series_id=None,
    episode_id=None,
    prior_cache=None,
    series_title=None,
    skip_guard=False,
):
    lines = [c["text"] for c in cues]
    if is_local_translate(cfg):
        context_lines = []
    elif series_id and episode_id and prior_cache is not None:
        if series_id not in prior_cache:
            prior_cache[series_id] = get_prior_context(cfg, series_id, episode_id)
        context_lines = prior_cache[series_id]
    else:
        context_lines = (
            get_prior_context(cfg, series_id, episode_id)
            if series_id and episode_id
            else []
        )
    out = chat_translate_batch(
        cfg, lines, target_lang, key, context_lines, series_title=series_title,
        skip_guard=skip_guard,
        emotions=[c.get("emotion") for c in cues],
    )
    if out is None:
        return None
    if is_local_translate(cfg):
        # merge-aware groups (start_idx, end_idx_excl, text); caller assembles cues
        return out
    if len(out) != len(lines):
        return None
    return [(i, i + 1, t) for i, t in enumerate(out)]


