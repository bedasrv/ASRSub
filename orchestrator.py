def target_sidecar_exists(media_path):
    """Cheap file-glob guard: does a target-language (Indonesian) subtitle
    sidecar already exist on disk next to the media file? Bazarr may have
    grabbed {stem}.id.srt / {stem}.id.hi.srt / {stem}.ind.srt /
    {stem}.ind.hi.srt independently of this pipeline; re-transcribing such an
    episode would waste GPU + API tokens. File-glob only: no probing, no
    transcription, no state writes. Returns the matched sidecar path or None."""
    d = os.path.dirname(media_path)
    basename_stem = os.path.splitext(os.path.basename(media_path))[0]
    pat = re.compile(
        r"^" + re.escape(basename_stem) + r"\.i(n)?d(\.hi)?\.srt$",
        re.IGNORECASE,
    )
    try:
        for name in os.listdir(d):
            if pat.match(name):
                return os.path.join(d, name)
    except OSError:
        return None
    return None


class _AudioStreams(list):
    """probe_audio result: a stream list with a format_duration side-channel
    for the ASR cache-key signature (kept off the stream dicts so
    choose_source stays untouched)."""

    format_duration = None


def probe_audio(path):
    p = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration:stream=index,codec_name,codec_type,channels,channel_layout,duration:stream_tags=language",
            "-of",
            "json",
            path,
        ],
        capture_output=True,
        text=True,
        timeout=300,
    )
    if p.returncode != 0:
        raise RuntimeError(f"ffprobe failed: {p.stderr.strip()}")
    data = json.loads(p.stdout)
    streams = _AudioStreams(
        s for s in data.get("streams", []) if s.get("codec_type") == "audio"
    )
    try:
        streams.format_duration = float((data.get("format") or {}).get("duration"))
    except (TypeError, ValueError):
        streams.format_duration = None
    return streams


def audio_stream_signature(streams):
    """Deterministic fingerprint of the audio streams (count + per-stream
    index/codec/lang/layout/duration + container format duration) -> short
    sha256. Sonarr REUSES episode ids across file upgrades, so the ASR cache
    key must key on the media's audio signature, never the episode id."""
    format_dur = getattr(streams, "format_duration", None)
    parts = [
        "{}:{}:{}:{}:{}".format(
            s.get("index"),
            s.get("codec_name"),
            (s.get("tags") or {}).get("language"),
            s.get("channel_layout") or s.get("channels"),
            s.get("duration"),
        )
        for s in streams
    ]
    sig = "count={};fmt_dur={};{}".format(len(parts), format_dur, ";".join(parts))
    return hashlib.sha256(sig.encode("utf-8")).hexdigest()[:32]


def choose_source(streams, target_lang):
    if not streams:
        return None
    lang_of = lambda s: s.get("tags", {}).get("language")
    if target_lang == "en":
        eng = next((s for s in streams if lang_of(s) == "eng"), None)
        if eng is not None:
            return {
                "stream_index": eng["index"],
                "asr_lang": "en",
                "needs_translate": False,
                "src_lang": "eng",
            }
    jpn = next((s for s in streams if lang_of(s) == "jpn"), None)
    s = jpn if jpn is not None else streams[0]
    tag = lang_of(s) or ""
    asr_lang = {"jpn": "ja", "eng": "en"}.get(tag, "en")
    return {
        "stream_index": s["index"],
        "asr_lang": asr_lang,
        "needs_translate": asr_lang != target_lang,
        "src_lang": tag or "?",
    }


