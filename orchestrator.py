def halt_on_error(cfg, stage, ep_desc, exc, extra=None):
    global _paused
    _paused = True
    rep = {
        "ts": time.strftime("%Y-%m-%d %H:%M:%S"),
        "stage": stage,
        "episode": ep_desc,
        "error": str(exc)[:500] or type(exc).__name__,
        "extra": extra or {},
    }
    report_dir = os.path.join(os.path.expanduser("~"), ".config", "asr-pipeline")
    os.makedirs(report_dir, exist_ok=True)
    dst = os.path.join(report_dir, "last_error.json")
    tmp = dst + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(rep, fh, indent=2)
    os.replace(tmp, dst)
    try:
        hist = os.path.join(report_dir, "error_history")
        os.makedirs(hist, exist_ok=True)
        import shutil

        shutil.copy2(
            dst, os.path.join(hist, f"error_{time.strftime('%Y%m%d_%H%M%S')}.json")
        )
    except Exception:
        pass
    log(
        f"[pipeline] PAUSED on error - fix first, resume via pctl resume (report: {dst})"
    )


def _order_pass_candidates(wanted_items, movie_items, regen_items, max_eps):
    """Pass priority ordering: series wanted first, then movie candidates,
    then series regen items; the combined list is capped at max_eps. Movies
    rank above regen so a heavy regen backlog cannot starve the movie track.
    Returns (ordered_candidates, movies_remaining) where movies_remaining is
    the FULL movie candidate count (pre-cap), used for the pass log."""
    movies_remaining = len(movie_items)
    return (
        (list(wanted_items) + list(movie_items) + list(regen_items))[:max_eps],
        movies_remaining,
    )


def run_pass():
    global _paused
    cfg = load_config()
    target_langs = set(cfg["TARGET_LANGS"])
    key = cfg.get("TRANSLATE_API_KEY", "")
    if not key:
        log(
            "WARNING: TRANSLATE_API_KEY is empty; any episode needing translation will FAIL"
        )

    pending_skip = consume_actions(cfg)

    entries = load_state()
    consec_errors = {}
    last_entry = {}
    for e in entries:
        k = (e.get("kind") or "series", e.get("sonarrEpisodeId"), e.get("language"))
        last_entry[k] = e
        if e.get("status") == "error":
            consec_errors[k] = consec_errors.get(k, 0) + 1
        else:
            consec_errors[k] = 0
    done_keys = {k for k, e in last_entry.items() if e.get("status") == "done"}

    try:
        wanted = get_wanted(cfg)
    except Exception as exc:
        log(f"ERROR fetching wanted list: {exc}")
        return {"fetch_error": True}
    total = wanted.get("total", 0)
    wanted_before = total

    candidates = []
    seen = set()
    for item in wanted.get("data", []):
        ep_id = item.get("sonarrEpisodeId")
        if ep_id in seen:
            continue
        missing = {m.get("code2") for m in item.get("missing_subtitles", [])}
        if missing & target_langs:
            candidates.append(item)
            seen.add(ep_id)
    excluded = parse_exclusions().union(pending_skip)
    if excluded:
        before = candidates
        candidates = [
            it for it in candidates if it.get("sonarrEpisodeId") not in excluded
        ]
        ex_list = sorted(excluded)
        if len(ex_list) > 10:
            ex_list = ex_list[:10] + [f"... +{len(excluded) - 10} more"]
        log(
            f"excluded this pass: {len(before) - len(candidates)} of {len(before)} episodes {ex_list}"
        )
    candidates.sort(key=lambda x: x["sonarrEpisodeId"])
    wanted_now = {it["sonarrEpisodeId"] for it in candidates}

    movie_cands = []
    if cfg.get("MOVIE_LIBRARY"):
        # Movie track: every Bazarr movie lacking AI-owned target subs is a
        # candidate (self-draining via the registry, like REGEN_LIBRARY);
        # movies rank between series wanted and series regen for the cap.
        movie_cands, movies_total = _movie_sweep(cfg, target_langs)
        log(f"movies total={movies_total}, movie candidates={len(movie_cands)}")

    regen_items = []
    if cfg.get("REGEN_LIBRARY"):
        # Library regeneration: every state-done (episode, language) pair is
        # a candidate again; wanted candidates keep priority and share the
        # MAX_EPS_PER_RUN cap (regen fills leftover slots). The per-item
        # registry check in the loop makes the drain resumable across passes.
        for (kind_, ep_id, lang), entry in last_entry.items():
            if kind_ != "series":
                continue  # movies drain via the sweep, never regen candidates
            if not isinstance(ep_id, int):
                continue
            if lang not in target_langs:
                continue
            if entry.get("status") != "done":
                continue
            if ep_id in excluded or ep_id in seen:
                continue  # wanted already covers this episode this pass
            registered = registry_by_episode(ep_id, lang)
            if registered and registered.get("source") in ("asr", "jpn", "eng"):
                continue  # already registered: leave the slot for unregistered pairs
            regen_items.append(
                {
                    "sonarrEpisodeId": ep_id,
                    "seriesTitle": entry.get("seriesTitle") or "?",
                    "missing_subtitles": [{"code2": lang}],
                    "regen": True,
                }
            )
        regen_items.sort(
            key=lambda x: (x["sonarrEpisodeId"], x["missing_subtitles"][0]["code2"])
        )

    candidates, movies_remaining = _order_pass_candidates(
        candidates, movie_cands, regen_items, cfg["MAX_EPS_PER_RUN"]
    )

    processed = done = skipped = failed = 0
    n_regen = sum(1 for it in candidates if it.get("regen"))
    n_movies = len(movie_cands)
    log(
        f"wanted total={total}, candidates for pass={len(candidates)} "
        f"(max={cfg['MAX_EPS_PER_RUN']}, regen candidates={n_regen}, "
        f"movie candidates={n_movies}, movies remaining={movies_remaining})"
    )

    prior_cache = {}
    futures = []
    # 1 worker is intentional: ASR is VRAM-bound (faster-whisper/SenseVoice
    # model + llama-server share one GPU); serial keeps GPU memory
    # deterministic and avoids OOM under concurrent ASR loads.
    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as pool:
        for item in candidates:
            ep_id = item["sonarrEpisodeId"]
            series = item.get("seriesTitle", "?")
            missing = {m.get("code2") for m in item.get("missing_subtitles", [])}
            langs = sorted(missing & target_langs)
            is_regen = bool(item.get("regen"))
            kind = "movie" if item.get("movie") else "series"
            for lang in langs:
                if (
                    not is_regen
                    and (kind, ep_id, lang) in done_keys
                    and ep_id not in wanted_now
                ):
                    log(f"skip: S?E? {series} [{lang}] already done (state)")
                    skipped += 1
                    continue
                if consec_errors.get((kind, ep_id, lang), 0) >= 2:
                    le = last_entry.get((kind, ep_id, lang)) or {}
                    last_ts = le.get("ts", "")
                    try:
                        last_dt = datetime.fromisoformat(last_ts.replace("Z", "+00:00"))
                        age_s = (datetime.now(timezone.utc) - last_dt).total_seconds()
                    except Exception:
                        age_s = 0
                    if age_s < 1800:
                        log(
                            f"park: {series} [{lang}] parked 30min after consecutive errors"
                        )
                        skipped += 1
                        continue
                processed += 1
                t0 = time.time()
                wav_path = srt_path = ""
                try:
                    if item.get("movie"):
                        movie_id = item["radarrId"]
                        title = item.get("movieTitle") or "?"
                        tag = "MOVIE"
                        container_path = item["path"]
                        media_path = map_path(container_path)
                        if not os.path.isfile(media_path):
                            log(
                                f"skip: MOVIE {title} [{lang}] file missing on NFS: {media_path}"
                            )
                            skipped += 1
                            continue
                        registered = registry_get(
                            os.path.splitext(media_path)[0], lang
                        )
                        if registered and registered.get("source") in (
                            "asr",
                            "jpn",
                            "eng",
                        ):
                            log(
                                f"movies: skip {title} [{lang}] already registered "
                                f"({registered.get('source')})"
                            )
                            skipped += 1
                            continue
                        if lang == "id":
                            target_sidecar = target_sidecar_exists(media_path)
                            if target_sidecar:
                                log(
                                    f"movies: skip {title} [id]: target-lang sidecar "
                                    f"exists ({os.path.basename(target_sidecar)})"
                                )
                                skipped += 1
                                continue
                        streams = probe_audio(media_path)
                        audio_id = audio_stream_signature(streams)
                        decision = choose_source(streams, lang)
                        if decision is None:
                            log(f"fail: MOVIE {title} [{lang}] no audio streams")
                            notify_hermes(
                                cfg,
                                movie_id,
                                lang,
                                title,
                                tag,
                                RuntimeError("no audio streams"),
                            )
                            halt_on_error(
                                cfg,
                                "no_audio_streams",
                                f"{title} [{lang}] MOVIE",
                                RuntimeError("no audio streams"),
                            )
                            failed += 1
                            append_state(
                                {
                                    "sonarrEpisodeId": movie_id,
                                    "language": lang,
                                    "status": "error",
                                    "elapsed_s": round(time.time() - t0, 1),
                                    "kind": "movie",
                                }
                            )
                            continue
                        src = decision["src_lang"]
                        log(f"movies: process {title} [{lang}]")
                        info = {
                            "episodeFile": {"path": container_path},
                            "title": title,
                            "seriesId": None,
                            "sonarrSeriesId": None,
                        }
                        ladder = detect_ladder_source(
                            cfg, media_path, lang, cfg["TMP_DIR"], movie_id, None
                        )
                        if ladder["kind"] != "asr":
                            log(
                                f"  MOVIE {title} [{ladder['kind']}->{lang}] ladder "
                                f"source {ladder['source_path']}"
                            )
                            futures.append(
                                pool.submit(
                                    process_ladder,
                                    cfg,
                                    key,
                                    movie_id,
                                    lang,
                                    title,
                                    tag,
                                    ladder,
                                    info,
                                    prior_cache=prior_cache,
                                    movie_id=movie_id,
                                )
                            )
                            continue
                        wav_path = os.path.join(
                            cfg["TMP_DIR"], f"movie_{movie_id}_{lang}.wav"
                        )
                        srt_path = os.path.join(
                            cfg["TMP_DIR"], f"movie_{movie_id}_{lang}.srt"
                        )
                        cached_cues = asr_cache_get(
                            audio_id, decision["asr_lang"], media_path
                        )
                        if cached_cues:
                            cues = cached_cues
                            log(
                                f"  MOVIE [{src}->{lang}] ASR cache hit "
                                "(skip extract+asr)"
                            )
                        else:
                            extract_wav(
                                media_path, decision["stream_index"], wav_path
                            )
                            t_asr = time.time()
                            if EMO_ENABLED and ASR_BACKEND == "sensevoice":
                                cues, wmeta = asr_cues(
                                    cfg, wav_path, decision["asr_lang"],
                                    return_windows=True,
                                )
                                cues = maybe_attach_emotion(cues, wav_path, wmeta)
                            else:
                                cues = asr_cues(
                                    cfg, wav_path, decision["asr_lang"]
                                )
                            asr_elapsed = time.time() - t_asr
                            asr_cache_put(
                                audio_id, decision["asr_lang"], media_path, cues
                            )
                        cues = [c for c in cues if c["text"].strip()]
                        if not cues:
                            raise RuntimeError("ASR returned no cues")
                        if not cached_cues:
                            log(
                                f"  MOVIE [{src}->{lang}] ASR {asr_elapsed:.0f}s, "
                                f"{len(cues)} cues"
                            )
                        futures.append(
                            pool.submit(
                                process_after_asr,
                                cfg,
                                key,
                                movie_id,
                                lang,
                                title,
                                tag,
                                src,
                                t0,
                                cues,
                                decision,
                                info,
                                wav_path,
                                srt_path,
                                prior_cache=prior_cache,
                                movie_id=movie_id,
                            )
                        )
                        continue
                    info = get_episode(cfg, ep_id)
                    season = info.get("seasonNumber", "?")
                    episode_num = info.get("episodeNumber", "?")
                    tag = (
                        f"S{season:02d}E{episode_num:02d}"
                        if isinstance(season, int) and isinstance(episode_num, int)
                        else f"S{season}E{episode_num}"
                    )
                    ef = info.get("episodeFile") or {}
                    if not info.get("hasFile") or not ef.get("path"):
                        log(f"skip: {tag} {series} [{lang}] hasFile=false or no path")
                        skipped += 1
                        continue
                    container_path = ef["path"]
                    media_path = map_path(container_path)
                    if not os.path.isfile(media_path):
                        log(
                            f"skip: {tag} {series} [{lang}] file missing on NFS: {media_path}"
                        )
                        skipped += 1
                        continue
                    if is_regen:
                        registered = registry_get(
                            os.path.splitext(media_path)[0], lang
                        )
                        if registered and registered.get("source") in (
                            "asr",
                            "jpn",
                            "eng",
                        ):
                            log(
                                f"regen: skip {tag} [{lang}] already registered "
                                f"({registered.get('source')})"
                            )
                            skipped += 1
                            continue
                        log(f"regen: process {tag} {series} [{lang}]")
                    if lang == "id" and not is_regen:
                        target_sidecar = target_sidecar_exists(media_path)
                        if target_sidecar:
                            log(
                                f"wanted: skip {tag} {series} [{lang}]: "
                                f"target-lang sidecar exists ({os.path.basename(target_sidecar)})"
                            )
                            skipped += 1
                            continue
                    streams = probe_audio(media_path)
                    audio_id = audio_stream_signature(streams)
                    decision = choose_source(streams, lang)
                    if decision is None:
                        log(f"fail: {tag} {series} [{lang}] no audio streams")
                        notify_hermes(
                            cfg,
                            ep_id,
                            lang,
                            series,
                            tag,
                            RuntimeError("no audio streams"),
                        )
                        halt_on_error(
                            cfg,
                            "no_audio_streams",
                            f"{series} [{lang}] {tag}",
                            RuntimeError("no audio streams"),
                        )
                        failed += 1
                        append_state(
                            {
                                "sonarrEpisodeId": ep_id,
                                "language": lang,
                                "status": "error",
                                "elapsed_s": round(time.time() - t0, 1),
                            }
                        )
                        continue
                    src = decision["src_lang"]
                    log(
                        f"{'regen: ' if is_regen else ''}proc: {tag} {series} [{src}->{lang}] source_stream={decision['stream_index']} asr_lang={decision['asr_lang']} needs_translate={decision['needs_translate']}"
                    )

                    os.makedirs(cfg["TMP_DIR"], exist_ok=True)

                    # Source ladder: a jpn/eng subtitle source beats ASR.
                    ladder = detect_ladder_source(
                        cfg,
                        media_path,
                        lang,
                        cfg["TMP_DIR"],
                        ep_id,
                        info.get("seriesId") or info.get("sonarrSeriesId"),
                    )
                    if ladder["kind"] != "asr":
                        log(
                            f"  {tag} {series} [{ladder['kind']}->{lang}] ladder source {ladder['source_path']}"
                        )
                        futures.append(
                            pool.submit(
                                process_ladder,
                                cfg,
                                key,
                                ep_id,
                                lang,
                                series,
                                tag,
                                ladder,
                                info,
                                prior_cache=prior_cache,
                            )
                        )
                        continue

                    wav_path = os.path.join(cfg["TMP_DIR"], f"{ep_id}_{lang}.wav")
                    srt_path = os.path.join(cfg["TMP_DIR"], f"{ep_id}_{lang}.srt")

                    cached_cues = asr_cache_get(audio_id, decision["asr_lang"], media_path)
                    if cached_cues:
                        cues = cached_cues
                        log(f"  {tag} [{src}->{lang}] ASR cache hit (skip extract+asr)")
                    else:
                        extract_wav(media_path, decision["stream_index"], wav_path)
                        t_asr = time.time()
                        if EMO_ENABLED and ASR_BACKEND == "sensevoice":
                            cues, wmeta = asr_cues(
                                cfg, wav_path, decision["asr_lang"],
                                return_windows=True,
                            )
                            cues = maybe_attach_emotion(cues, wav_path, wmeta)
                        else:
                            cues = asr_cues(cfg, wav_path, decision["asr_lang"])
                        asr_elapsed = time.time() - t_asr
                        asr_cache_put(audio_id, decision["asr_lang"], media_path, cues)
                    cues = [c for c in cues if c["text"].strip()]
                    if not cues:
                        raise RuntimeError("ASR returned no cues")
                    if not cached_cues:
                        log(
                            f"  {tag} [{src}->{lang}] ASR {asr_elapsed:.0f}s, {len(cues)} cues"
                        )
                    futures.append(
                        pool.submit(
                            process_after_asr,
                            cfg,
                            key,
                            ep_id,
                            lang,
                            series,
                            tag,
                            src,
                            t0,
                            cues,
                            decision,
                            info,
                            wav_path,
                            srt_path,
                            prior_cache=prior_cache,
                        )
                    )
                except Exception as exc:
                    failed += 1
                    for f in (wav_path, srt_path):
                        if f:
                            try:
                                os.remove(f)
                            except OSError:
                                pass
                    append_state(
                        {
                            "sonarrEpisodeId": ep_id,
                            "language": lang,
                            "status": "error",
                            "elapsed_s": round(time.time() - t0, 1),
                            **({"kind": "movie"} if item.get("movie") else {}),
                        }
                    )
                    log(f"fail: {series} [{lang}] {exc}")
                    notify_hermes(cfg, ep_id, lang, series, tag, exc)
                    halt_on_error(
                        cfg, "process_submit", f"{series} [{lang}] {tag}", exc
                    )

        for fut in as_completed(futures):
            if fut.result() == "done":
                done += 1
            else:
                failed += 1

        # Auto-upgrade phase: better jpn sources for already-produced AI subs.
        try:
            upgrades = run_upgrades(cfg, key, prior_cache=prior_cache)
        except Exception as exc:
            log(f"upgrade pass failed: {exc}")
            upgrades = {"upgraded": 0, "checked": 0}
        log(
            f"upgrade summary: upgraded={upgrades['upgraded']} checked={upgrades['checked']}"
        )

    if processed == 0:
        wanted_after = wanted_before  # nothing changed; skip redundant API call
        movies_remaining = None
    else:
        try:
            wanted_after = get_wanted(cfg).get("total", 0)
        except Exception:
            wanted_after = None
        movies_remaining = None
        if cfg.get("MOVIE_LIBRARY"):
            try:
                movies_remaining = len(movie_candidates(cfg, target_langs))
            except Exception:
                movies_remaining = None
    log(
        f"pass summary: processed={processed} done={done} skipped={skipped} failed={failed} "
        f"wanted_before={wanted_before} wanted_after={wanted_after} "
        f"movies_remaining={movies_remaining}"
    )
    return {
        "processed": processed,
        "done": done,
        "skipped": skipped,
        "failed": failed,
        "wanted_before": wanted_before,
        "wanted_after": wanted_after,
        "movies_remaining": movies_remaining,
    }


SECRET_KEY_HINTS = ("KEY", "TOKEN", "SECRET", "PASSWORD", "PASS", "AUTH", "CRED")


def _mask_secrets(cfg):
    return {
        k: ("***" if any(h in k.upper() for h in SECRET_KEY_HINTS) else v)
        for k, v in cfg.items()
    }


def _read_overrides():
    if not os.path.exists(OVERRIDE_FILE):
        return {}
    try:
        with open(OVERRIDE_FILE, "r", encoding="utf-8") as fh:
            data = json.loads(fh.read())
        return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def _write_overrides(ov):
    os.makedirs(os.path.dirname(OVERRIDE_FILE), exist_ok=True)
    tmp = OVERRIDE_FILE + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(ov, ensure_ascii=False, indent=2) + "\n")
    os.replace(tmp, OVERRIDE_FILE)


class ControlHandler(BaseHTTPRequestHandler):
    def _send_json(self, code, obj):
        body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _check_auth(self):
        if not CONTROL_API_KEY:
            self._send_json(401, {"error": "CONTROL_API_KEY not configured"})
            return False
        # X-API-Key: dashboard/control_api_v2 proxy; X-Control-Key: Sonarr
        # webhook notification headers (configured on the ASRSub Wake
        # notification). Either must match the shared CONTROL_API_KEY.
        if (
            self.headers.get("X-API-Key") != CONTROL_API_KEY
            and self.headers.get("X-Control-Key") != CONTROL_API_KEY
        ):
            self._send_json(401, {"error": "unauthorized"})
            return False
        return True

    def _state_counts(self):
        # Count the LATEST entry per (kind, sonarrEpisodeId, language):
        # state.jsonl is append-only, every failed attempt adds a row, so
        # summing every row would report lifetime error counts instead of
        # current state. Kind keeps movie rows (sonarrEpisodeId == radarrId,
        # small ids that collide with series episodes) from overwriting
        # series rows of the same id.
        latest = {}
        for e in load_state():
            key = (e.get("kind") or "series", e.get("sonarrEpisodeId"), e.get("language"))
            cur = latest.get(key)
            if cur is None or (e.get("ts") or "") >= (cur.get("ts") or ""):
                latest[key] = e
        counts = {"done": 0, "error": 0, "pending": 0, "total": len(latest)}
        for e in latest.values():
            st = e.get("status")
            if st == "done" or st == "error":
                counts[st] += 1
            else:
                counts["pending"] += 1
        return counts

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path not in ("/health", "/status"):
            if not self._check_auth():
                return
        if path == "/health":
            self._send_json(200, {"ok": True})
        elif path == "/status":
            movies_remaining = 0
            try:
                status_cfg = load_config()
                if status_cfg.get("MOVIE_LIBRARY"):
                    movies_remaining = len(
                        movie_candidates(status_cfg, set(status_cfg["TARGET_LANGS"]))
                    )
            except Exception:
                movies_remaining = 0
            self._send_json(
                200,
                {
                    "uptime_s": int(
                        (datetime.now(timezone.utc) - _started_at).total_seconds()
                    ),
                    "paused": _paused,
                    "run_once_requested": _run_once_requested,
                    "last_pass": _last_pass_stats,
                    "movies_remaining": movies_remaining,
                    "state_counts": self._state_counts(),
                    "consecutive_failures": _consecutive_failures,
                    "started_at": _started_at.isoformat(),
                },
            )
        elif path == "/config":
            self._send_json(200, _mask_secrets(load_config()))
        elif path == "/sonarr-webhook":
            WAKE_EVENT.set()
            self._send_json(200, {"ok": True})
        else:
            self._send_json(404, {"error": "not found"})

    def do_POST(self):
        global _paused, _run_once_requested
        path = self.path.split("?", 1)[0]
        if not self._check_auth():
            return
        if path == "/sonarr-webhook":
            WAKE_EVENT.set()
            self._send_json(200, {"ok": True})
            return
        if path == "/wake":
            WAKE_EVENT.set()
            self._send_json(200, {"ok": True})
            return
        if path == "/tdarr-webhook":
            try:
                raw = self.rfile.read(int(self.headers.get("Content-Length", "0")))
                body = json.loads(raw.decode("utf-8") or "{}")
                file_path = body.get("file") or ""
                tdarr_id = body.get("_id") or ""
            except Exception:
                file_path, tdarr_id = "", ""
            if file_path:
                threading.Thread(
                    target=extract_subtitle_sidecars,
                    args=(file_path, tdarr_id),
                    daemon=True,
                ).start()
            else:
                log("tdarr-webhook: received POST without 'file' field")
            self._send_json(200, {"ok": True})
            return
        if path == "/config":
            try:
                raw = self.rfile.read(int(self.headers.get("Content-Length", "0")))
                body = json.loads(raw.decode("utf-8") or "{}")
            except Exception as exc:
                self._send_json(400, {"error": f"invalid JSON body: {exc}"})
                return
            if not isinstance(body, dict):
                self._send_json(400, {"error": "body must be a JSON object"})
                return
            ov = _read_overrides()
            applied = {}
            for k, v in body.items():
                if v is None:
                    ov.pop(k, None)
                    applied[k] = None
                else:
                    ov[str(k)] = str(v)
                    applied[str(k)] = str(v)
            _write_overrides(ov)
            WAKE_EVENT.set()
            self._send_json(200, {"ok": True, "applied": _mask_secrets(applied)})
        elif path == "/pause":
            _paused = True
            self._send_json(200, {"ok": True, "paused": True})
        elif path == "/resume":
            _paused = False
            WAKE_EVENT.set()
            try:
                report_dir = os.path.join(
                    os.path.expanduser("~"), ".config", "asr-pipeline"
                )
                dst = os.path.join(report_dir, "last_error.json")
                if os.path.exists(dst):
                    hist = os.path.join(report_dir, "error_history")
                    os.makedirs(hist, exist_ok=True)
                    os.replace(
                        dst,
                        os.path.join(
                            hist, f"error_{time.strftime('%Y%m%d_%H%M%S')}.json"
                        ),
                    )
                    log("cleared error report")
            except Exception:
                pass
            self._send_json(200, {"ok": True, "paused": False})
        elif path == "/run-once":
            _run_once_requested = True
            WAKE_EVENT.set()
            self._send_json(200, {"ok": True, "run_once_requested": True})
        else:
            self._send_json(404, {"error": "not found"})

    def log_message(self, *args):
        pass


def start_webhook_listener():
    try:
        srv = ThreadingHTTPServer(("0.0.0.0", WEBHOOK_PORT), ControlHandler)
    except OSError as exc:
        log(
            f"webhook listener unavailable on :{WEBHOOK_PORT} ({exc}); continuing without it"
        )
        return
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    log(
        f"control API + webhook listener on :{WEBHOOK_PORT} (GET /status, /config, /health; POST /config /pause /resume /run-once /wake /sonarr-webhook /tdarr-webhook)"
    )


def main():
    lock_path = "/home/user/.config/asr-pipeline/orchestrator.lock"
    lock_fd = open(lock_path, "w")
    try:
        fcntl.flock(lock_fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        log("another orchestrator instance running, exiting")
        return 0
    global _consecutive_failures, _last_pass_stats, _paused, _run_once_requested
    cfg = load_config()
    start_webhook_listener()
    signal.signal(signal.SIGTERM, _handle_sigterm)
    _consecutive_failures = 0
    # startup orphan GC: prune ghost/fileless state rows before the first pass
    try:
        gc_state(cfg, load_state())
    except Exception as exc:
        log(f"GC error at startup: {exc}")
    while True:
        if _paused and not _run_once_requested:
            if _stop_requested:
                log("stop requested while paused; exiting")
                return 0
            log("paused; waiting")
            WAKE_EVENT.wait(timeout=900)
            WAKE_EVENT.clear()
            continue
        try:
            stats = run_pass()
        except Exception as exc:
            halt_on_error(cfg, "pass", "run_pass", exc)
            stats = {"fetch_error": True}
        _last_pass_stats = stats
        _run_once_requested = False
        if _stop_requested:
            log("stop requested, exiting after pass")
            return 0
        if stats.get("fetch_error"):
            _consecutive_failures += 1
        else:
            _consecutive_failures = 0
        remaining = stats.get("wanted_after")
        if remaining is None:
            remaining = stats.get("wanted_before", 0)
        movies_remaining = stats.get("movies_remaining") or 0
        processed = stats.get("processed") or 0
        failed = stats.get("failed") or 0
        busy = (
            processed > 0
            and ((remaining or 0) > 0 or (movies_remaining or 0) > 0)
        ) or failed > 0
        # idle pass (nothing processed): sweep orphan GC for episode ids not
        # yet checked this daemon lifetime; Sonarr down => logged, retried next
        if processed == 0 and not _stop_requested:
            try:
                gc_state(cfg, load_state())
            except Exception as exc:
                log(f"GC error after idle pass: {exc}")
        if _consecutive_failures >= 3:
            delay = 900  # Bazarr/API down - stop hot-looping
        elif busy:
            delay = 60  # backlog or failures - re-check soon
        else:
            delay = 900  # idle
        log(
            f"sleeping {delay}s until next pass (busy={busy}, consecutive_failures={_consecutive_failures})"
        )
        WAKE_EVENT.wait(timeout=delay)
        WAKE_EVENT.clear()


if __name__ == "__main__":
    sys.exit(main())
